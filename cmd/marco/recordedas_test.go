package main

// A RUN RECORD SAYS HOW THE ROUTINE IT PERFORMED WAS RECORDED.
//
// The mode field has existed since the record did, and until now it said `unstated` for every run
// because nothing could put another word there. It is read off the SAME SINGLE READ as the digest
// and the contract — one look at the file, before the reference is claimed — so the record cannot
// cite one routine's source and another's mode.
//
// Why it is in the record at all: a person reporting a problem with a routine wants to know
// whether its presses were aimed at a coordinate or found by matching a picture, and the two fail
// in different ways. A record that said `unstated` about a routine whose file states a mode would
// be withholding the answer at the moment it was asked for.
//
// See [[ADR-254-what-a-recording-captures-is-stated]].

import (
	"strings"
	"testing"

	"github.com/chaynes-simpleclouds/marco/internal/orchestrator"
)

// aCoordinateRoutine is `aGuardedRoutine` with the line a coordinate-mode save writes.
//
// Built from the same constant rather than retyped, so a change to the fixture cannot leave this
// testing a routine the rest of the file no longer describes.
var aCoordinateRoutine = "// Auto-generated by `marco learn \"ark graphics\"`. Edit freely.\n" +
	"// Recorded as: coordinates.\n" + aGuardedRoutine

// THE RECORD CARRIES THE WORD THE SOURCE STATES.
func TestTheRecordSaysWhatTheRoutineWasRecordedAs(t *testing.T) {
	d, rt := aLibraryWith(t, aCoordinateRoutine)
	_, _, ref := aRunOf(t, d, rt)
	m, raw := recordAt(t, ref.ID)
	if m["mode"] != string(orchestrator.Coordinates) {
		t.Errorf("the record says the run was performed in mode %v, and the source "+
			"it ran states %q:\n%s", m["mode"], orchestrator.Coordinates, raw)
	}
}

// AND SAYS `unstated` WHEN THE SOURCE SAYS NOTHING, which is every routine saved before this.
//
// Not a guess from an environment variable, and not an empty field either: the record's reader is
// a person, and a blank where a word belongs reads as a record that failed to write one.
func TestTheRecordSaysUnstatedWhenTheRoutineDoesNotSay(t *testing.T) {
	d, rt := aLibraryWith(t, aGuardedRoutine)
	_, _, ref := aRunOf(t, d, rt)
	m, raw := recordAt(t, ref.ID)
	if m["mode"] != modeUnstated {
		t.Errorf("a routine whose source states no mode recorded its mode as %v:\n%s",
			m["mode"], raw)
	}
}

// AND THE MODE IS IN THE RECORD BEFORE THE FIRST INPUT, like the rest of the identity.
//
// The same reason `build`, `source_digest` and `contract` are: the attempt that most needs
// identifying is the one that never finished, and a mode added after the performance returned
// would be absent from exactly that record. Measured from inside the first host action.
func TestTheRecordInFlightAlreadySaysHowItWasRecorded(t *testing.T) {
	d, rt := aLibraryWith(t, aCoordinateRoutine)
	host := &aHostThatLooksForItsOwnRecord{}
	d.Hosts["*"] = host
	_, _, ref := aRunOf(t, d, rt)
	if ref.ID == "" {
		t.Fatal("the run cited nothing, so there is no record to look in")
	}
	if host.inFlight == nil {
		t.Fatal("the host never found a record while it was running, so this " +
			"proves nothing about what was in it")
	}
	if got := host.inFlight["mode"]; got != string(orchestrator.Coordinates) {
		t.Errorf("while the routine was running its record said mode %v, not %q",
			got, orchestrator.Coordinates)
	}
	// AND THE FINISHED RECORD AGREES. Two readings of one file would be two answers,
	// and the one a person gets is whichever the run reached.
	done, raw := recordAt(t, ref.ID)
	if done["mode"] != host.inFlight["mode"] {
		t.Errorf("the mode changed between the reservation (%v) and the finished "+
			"record (%v):\n%s", host.inFlight["mode"], done["mode"], raw)
	}
}

// AND A MODE NOBODY WROTE DOWN IS NOT INVENTED FROM THE ENVIRONMENT.
//
// `$MARCO_CV` is a setting of whichever process is running, and `marco do` is not the process
// that recorded anything. Reading it here would put a word in the record describing a shell that
// opened after the routine was made.
func TestTheRecordedModeIsNotTakenFromThisProcessEnvironment(t *testing.T) {
	t.Setenv("MARCO_CV", "on")
	t.Setenv("MARCO_ANCHORS", "1")
	d, rt := aLibraryWith(t, aGuardedRoutine)
	_, _, ref := aRunOf(t, d, rt)
	m, raw := recordAt(t, ref.ID)
	if m["mode"] != modeUnstated {
		t.Errorf("the record read its mode out of this process's environment: %v\n%s",
			m["mode"], raw)
	}
	if strings.Contains(raw, "anchors") || strings.Contains(raw, "MARCO_CV") {
		t.Errorf("an environment variable reached a durable record:\n%s", raw)
	}
}
