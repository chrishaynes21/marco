package main

// A RUN RECORD SAYS WHICH GENERATION OF THE GENERATOR'S RULES WROTE THE ROUTINE IT PERFORMED.
//
// Which is the question somebody asks when a routine behaves differently on two machines, or
// behaved differently last month, and nothing else in the record can answer it: `build` says
// which `marco` ran, and a routine's generation is a fact about the FILE. The two come apart
// exactly when it matters — a current build performing a routine written years of rules ago, and
// an older build performing one written by a newer.
//
// Both halves are carried: what the file SAYS, verbatim, and what this build made of it. A record
// holding only the verdict would turn a later build's routine into the word `unknown` and lose the
// one fact that identifies it to whoever can explain it.
//
// Read off the same single read as the digest, the mode and the contract — see `take`.
//
// See [[ADR-262-a-routine-states-which-generation-wrote-it]].

import (
	"fmt"
	"os"
	"strings"
	"testing"

	"github.com/chaynes-simpleclouds/marco/internal/orchestrator"
)

// aRoutineStating is `aGuardedRoutine` with a generation line in front of it.
//
// Built from the same constant the rest of this package uses, so a change to the fixture cannot
// leave this testing a routine nothing else describes.
func aRoutineStating(line string) string {
	return "// Auto-generated by `marco learn \"ark graphics\"`. Edit freely.\n" +
		line + "\n" + aGuardedRoutine
}

// THE RECORD CARRIES WHAT THE SOURCE STATES, AND THIS BUILD'S READING OF IT.
func TestTheRecordSaysWhichGenerationWroteTheRoutine(t *testing.T) {
	now := fmt.Sprint(orchestrator.GenerationNow())
	d, rt := aLibraryWith(t, aRoutineStating("// Generation: "+now+"."))
	_, _, ref := aRunOf(t, d, rt)
	m, raw := recordAt(t, ref.ID)

	if m["generation"] != now {
		t.Errorf("the record says the routine states generation %v, and its source "+
			"states %q:\n%s", m["generation"], now, raw)
	}
	if m["generation_reading"] != string(orchestrator.GenerationCurrent) {
		t.Errorf("a routine stating this build's own generation is recorded as %v",
			m["generation_reading"])
	}
}

// AND A ROUTINE THAT STATES NOTHING IS RECORDED AS STATING NOTHING.
//
// Every routine saved before the line existed, and every one somebody wrote by hand. The reading
// is the word `unstated`; the declared value is ABSENT, because the file declared none and a
// record that wrote something there would be inventing a provenance for somebody's file.
func TestTheRecordSaysUnstatedWhenTheRoutineNamesNoGeneration(t *testing.T) {
	d, rt := aLibraryWith(t, aGuardedRoutine)
	_, _, ref := aRunOf(t, d, rt)
	m, raw := recordAt(t, ref.ID)

	if m["generation_reading"] != string(orchestrator.GenerationUnstated) {
		t.Errorf("a routine whose source states no generation recorded %v:\n%s",
			m["generation_reading"], raw)
	}
	if _, there := m["generation"]; there {
		t.Errorf("the record declares a generation of %v for a routine that states "+
			"none:\n%s", m["generation"], raw)
	}
}

// AND AN OLDER EXECUTOR MEETING A NEWER ROUTINE DOES NOT RECORD IT AS ITS OWN.
//
// The reading that is silent when it is wrong. `current` would be this build writing down that it
// wrote a file it has never been able to read, in the one artifact a person cites when they
// cannot work out why a routine behaved differently somewhere else — and the declared value is
// what tells them which build to go and ask.
func TestTheRecordDoesNotRelabelALaterGenerationAsItsOwn(t *testing.T) {
	ahead := fmt.Sprint(orchestrator.GenerationNow() + 3)
	d, rt := aLibraryWith(t, aRoutineStating("// Generation: "+ahead+"."))
	_, out, ref := aRunOf(t, d, rt)
	m, raw := recordAt(t, ref.ID)

	if m["generation_reading"] == string(orchestrator.GenerationCurrent) {
		t.Errorf("a routine from a later build is recorded as this build's own "+
			"generation:\n%s", raw)
	}
	if m["generation_reading"] != string(orchestrator.GenerationUnknown) {
		t.Errorf("a routine stating generation %s is recorded as %v", ahead,
			m["generation_reading"])
	}
	if m["generation"] != ahead {
		t.Errorf("the file states generation %s and the record declares %v — which "+
			"is the only fact in it that identifies the routine:\n%s", ahead,
			m["generation"], raw)
	}
	// AND IT RAN EXACTLY AS IT WOULD HAVE WITHOUT THE LINE.
	//
	// An unknown generation stays inspectable and playable under the rules it always had.
	// Asserted against a CONTROL rather than by eye: the same routine with no stamp at all
	// is performed, and the two runs have to reach the same outcome for the same stated
	// reason. A build that refused, or warned, or took a different path over a comment it
	// could not read would show up here as two different sentences.
	plainDeps, plainRt := aLibraryWith(t, aGuardedRoutine)
	_, plainOut, plainRef := aRunOf(t, plainDeps, plainRt)
	plain, _ := recordAt(t, plainRef.ID)
	if m["outcome"] != plain["outcome"] {
		t.Errorf("the routine stating generation %s ended %v and the same routine "+
			"with no stamp ended %v, so the line changed what the run did",
			ahead, m["outcome"], plain["outcome"])
	}
	if m["because"] != plain["because"] {
		t.Errorf("the stamped routine stopped because %v and the unstamped one "+
			"because %v", m["because"], plain["because"])
	}
	if m["input_actions"] != plain["input_actions"] {
		t.Errorf("the stamped routine asked for %v input action(s) and the unstamped "+
			"one for %v", m["input_actions"], plain["input_actions"])
	}
	if plainOut != out {
		t.Errorf("the stamped run reported %q and the unstamped one %q", out, plainOut)
	}
}

// AND A STAMP THIS BUILD CANNOT PARSE IS RECORDED AS WHAT IT SAID, NOT AS NOTHING.
func TestTheRecordKeepsAMalformedStampVerbatim(t *testing.T) {
	d, rt := aLibraryWith(t, aRoutineStating("// Generation: two."))
	_, _, ref := aRunOf(t, d, rt)
	m, raw := recordAt(t, ref.ID)

	if m["generation"] != "two" {
		t.Errorf("the record declares %v for a routine whose file says `two`:\n%s",
			m["generation"], raw)
	}
	if m["generation_reading"] != string(orchestrator.GenerationUnknown) {
		t.Errorf("a malformed stamp is recorded as %v", m["generation_reading"])
	}
}

// AND THE GENERATION IS IN THE RECORD BEFORE THE FIRST INPUT, like the rest of the identity.
//
// The same reason `build`, `source_digest`, `contract` and `mode` are: the attempt that most
// needs identifying is the one that never finished, and a field added after the performance
// returned is absent from exactly that record. Measured from inside the first host action.
func TestTheRecordInFlightAlreadySaysWhichGenerationWroteIt(t *testing.T) {
	now := fmt.Sprint(orchestrator.GenerationNow())
	d, rt := aLibraryWith(t, aRoutineStating("// Generation: "+now+"."))
	host := &aHostThatLooksForItsOwnRecord{}
	d.Hosts["*"] = host
	_, _, ref := aRunOf(t, d, rt)

	if ref.ID == "" {
		t.Fatal("the run cited nothing, so there is no record to look in")
	}
	if host.inFlight == nil {
		t.Fatal("the host never found a record while it was running, so this " +
			"proves nothing about what was in it")
	}
	if got := host.inFlight["generation"]; got != now {
		t.Errorf("while the routine was running its record declared generation %v, "+
			"not %q", got, now)
	}
	if got := host.inFlight["generation_reading"]; got !=
		string(orchestrator.GenerationCurrent) {
		t.Errorf("while the routine was running its record read its generation as %v",
			got)
	}
}

// AND A ROUTINE THE COMMAND COULD NOT READ CLAIMS NEITHER.
//
// `unstated` is a reading of a real file. Writing it for a file nobody opened would be a reading
// of something nobody read — the distinction `contractUnstated` exists for, one field up.
func TestARoutineThatCouldNotBeReadStatesNoGenerationEitherWay(t *testing.T) {
	d, rt := aLibraryWith(t, aGuardedRoutine)
	// THE FILE, GONE BETWEEN THE SAVE AND THE RUN. Which is a state a library is
	// really in: somebody deleted a routine, or the store is on a drive that went away.
	if err := os.Remove(d.Reg.Path(rt)); err != nil {
		t.Fatal(err)
	}
	_, out, ref := aRunOf(t, d, rt)
	if out != OutcomeFailed {
		t.Fatalf("a routine whose file is gone reported %q", out)
	}
	m, raw := recordAt(t, ref.ID)
	if _, there := m["generation"]; there {
		t.Errorf("the record declares generation %v for a file nobody read:\n%s",
			m["generation"], raw)
	}
	if _, there := m["generation_reading"]; there {
		t.Errorf("the record reads the generation of a file nobody read as %v:\n%s",
			m["generation_reading"], raw)
	}
	// AND IT STILL SAYS WHAT WENT WRONG, which is what the record is for.
	if because, _ := m["because"].(string); !strings.Contains(because, rt.Slug) &&
		because == "" {
		t.Errorf("the record says nothing about why:\n%s", raw)
	}
}
