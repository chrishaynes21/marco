package main

// A ROUTINE THAT TYPES TEXT SOMEBODY SUPPLIES, THROUGH THE ONE DOOR.
//
// `internal/routes` holds the rules about which values are missing and which cannot be written
// down. These are about what the PRODUCT does with them: a routine invoked without its text is
// REFUSED rather than performed, one invoked with it types exactly those characters, and the text
// does not reach the durable record of the attempt.
//
// The last one is the half that is easy to lose. A value can be kept out of the route, the
// recording and the sidecars and still be written into the run record, a log line or a refusal's
// own sentence — and a run record is the one file somebody is told to go and cite.
//
// See [[Text-arguments-proposal-2026-10-30]].

import (
	"io"
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/chaynes-simpleclouds/marco/internal/invoke"
	"github.com/chaynes-simpleclouds/marco/internal/orchestrator"
	"github.com/chaynes-simpleclouds/marco/internal/routes"
	"github.com/chaynes-simpleclouds/marco/internal/runtime"
)

// aRoutineThatTypesAValue is a saved routine with one text argument, wired the way `marco do`
// wires itself: a recording host in place of the OS, and the authority door saying yes so that
// nothing but the argument rules can be the reason it does not run.
func aRoutineThatTypesAValue(t *testing.T) (orchestrator.Deps, *recordHost) {
	t.Helper()
	t.Setenv("MARCO_HOME", t.TempDir())
	t.Setenv("MARCO_NO_PANIC_STOP", "1")
	reg := routes.Registry{Dir: t.TempDir()}
	rt := routes.Route{App: "notepad", Slug: "write-a-note"}
	src := "// Auto-generated by `marco learn \"write a note with message\"`.\n" +
		"use os.\n\nthe App is a script.\n\n" +
		"do OS's Type with \"{{message}}\"...\n" +
		"    when ok?\n        log \"done\".\n    or?\n        log that's error.\n"
	if err := reg.Save(rt, src); err != nil {
		t.Fatal(err)
	}
	host := &recordHost{}
	return orchestrator.Deps{
		Reg:       reg,
		Hosts:     map[string]runtime.Host{"*": host},
		In:        strings.NewReader(""),
		Out:       &strings.Builder{},
		App:       func() string { return "notepad" },
		Authority: allowGate{},
	}, host
}

// typed is what the host was asked to type, in order.
//
// EMPTY TEXT IS A VALUE HERE TOO, and the harness spells it by omission: `recordHost` appends
// " with <input>" only when the input is non-empty, so a Type of nothing records as bare
// "OS's Type". A helper that only stripped the prefix would read that as "no Type happened",
// which is the same missing-versus-empty confusion the contract is about — one layer down, in the
// instrument.
func typed(h *recordHost) []string {
	var out []string
	for _, c := range h.calls {
		switch {
		case c == "OS's Type":
			out = append(out, "")
		case strings.HasPrefix(c, "OS's Type with "):
			out = append(out, strings.TrimPrefix(c, "OS's Type with "))
		}
	}
	return out
}

// saidOnStdout runs fn with the process's own stdout captured, and returns what was printed.
//
// REQUIRED RATHER THAN CONVENIENT. A refusal at this layer is printed on `os.Stdout` — the same
// place the authority door prints its own sentence, because that is the stream every front end
// reads — and NOT on `Deps.Out`. A test that read `Deps.Out` would see nothing and would pass
// whatever the sentence said, which is how "it does not repeat the value" came to be an assertion
// about an empty string.
func saidOnStdout(t *testing.T, fn func()) string {
	t.Helper()
	r, w, err := os.Pipe()
	if err != nil {
		t.Fatal(err)
	}
	was := os.Stdout
	os.Stdout = w
	done := make(chan string, 1)
	go func() {
		b, _ := io.ReadAll(r)
		done <- string(b)
	}()
	fn()
	os.Stdout = was
	_ = w.Close()
	got := <-done
	_ = r.Close()
	return got
}

// INVOKED WITHOUT ITS TEXT, THE ROUTINE IS REFUSED AND PRESSES NOTHING.
//
// What it did before: typed nothing where the value goes and reported `performed`. Refused is a
// different word from failed on purpose — nothing was attempted.
func TestARoutineNeedingTextIsRefusedAtTheDoor(t *testing.T) {
	d, host := aRoutineThatTypesAValue(t)
	out, err := doAsProduct(t, d, "write a note", nil, nil)
	if err != nil {
		t.Fatalf("the refusal came back as an error: %v", err)
	}
	if out != OutcomeRefused {
		t.Errorf("the invocation came back %q, not refused", out)
	}
	if len(host.pressed()) != 0 {
		t.Errorf("it pressed %v", host.pressed())
	}
}

// AND WITH ITS TEXT IT TYPES EXACTLY THOSE CHARACTERS.
//
// The control, and it earns its place: a contract that refuses everything passes the case above.
func TestARoutineGivenItsTextTypesIt(t *testing.T) {
	d, host := aRoutineThatTypesAValue(t)
	out, err := doAsProduct(t, d, "write a note", map[string]string{
		"message": `he said "hello" \ there`}, nil)
	if err != nil {
		t.Fatalf("the run failed: %v", err)
	}
	if out != OutcomePerformed {
		t.Fatalf("the invocation came back %q", out)
	}
	if got := typed(host); len(got) != 1 || got[0] != `he said "hello" \ there` {
		t.Errorf("it typed %q", got)
	}
}

// AND AN EXPLICITLY EMPTY VALUE RUNS, TYPING NOTHING.
//
// THE CASE A LENGTH TEST GETS WRONG, at the layer where it would be felt: clearing a field is a
// thing people do, and refusing it would refuse the one thing they meant.
func TestAnExplicitlyEmptyValueRunsAndTypesNothing(t *testing.T) {
	d, host := aRoutineThatTypesAValue(t)
	out, err := doAsProduct(t, d, "write a note", map[string]string{"message": ""}, nil)
	if err != nil {
		t.Fatalf("the run failed: %v", err)
	}
	if out != OutcomePerformed {
		t.Fatalf("an empty value somebody gave on purpose came back %q", out)
	}
	if got := typed(host); len(got) != 1 || got[0] != "" {
		t.Errorf("it typed %q", got)
	}
}

// AND THE TEXT IS IN NOTHING DURABLE.
//
// The run record is the one file somebody is told to go and cite, and it is written by the
// attempt rather than by the person — so a value that reached it would be a value nobody chose to
// keep. The route on disk is checked too, because `ApplyArgs` fills a COPY and a substitution
// that wrote back would turn a routine into a template that had been edited.
func TestTheSuppliedTextIsNotInAnyDurableRecord(t *testing.T) {
	const secretish = "my-private-note-42"
	d, _ := aRoutineThatTypesAValue(t)
	if out, err := doAsProduct(t, d, "write a note",
		map[string]string{"message": secretish}, nil); err != nil || out != OutcomePerformed {
		t.Fatalf("the run came back %q: %v", out, err)
	}
	// THE ROUTE IS UNCHANGED: the placeholder is still a placeholder.
	src, err := os.ReadFile(d.Reg.Path(routes.Route{App: "notepad", Slug: "write-a-note"}))
	if err != nil {
		t.Fatal(err)
	}
	if strings.Contains(string(src), secretish) {
		t.Error("the value was written into the play")
	}
	if !strings.Contains(string(src), "{{message}}") {
		t.Error("the placeholder was consumed, so the play can only run once")
	}
	// AND NOTHING UNDER THE STORE HOLDS IT — run records, journals, anything the attempt
	// wrote. Walked rather than named, because a record this test does not know about is
	// exactly the one that would keep it.
	home := os.Getenv("MARCO_HOME")
	var found []string
	err = filepath.WalkDir(home, func(path string, de os.DirEntry, err error) error {
		if err != nil || de.IsDir() {
			return nil
		}
		b, readErr := os.ReadFile(path)
		if readErr == nil && strings.Contains(string(b), secretish) {
			rel, _ := filepath.Rel(home, path)
			found = append(found, rel)
		}
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}
	if len(found) > 0 {
		t.Errorf("the supplied text was written into %v", found)
	}
}

// AND A REFUSAL NAMES THE ARGUMENT AND NOT ITS VALUE.
//
// A refusal is a diagnostic: it is printed, logged, and read by whoever is working out what
// happened. Naming the argument is what they need; repeating the text is how it ends up in a
// terminal scrollback and a log file.
func TestARefusalNamesTheArgumentAndNotTheValue(t *testing.T) {
	const secretish = "my-private-note-42"
	d, _ := aRoutineThatTypesAValue(t)
	var out Outcome
	var err error
	// A VALUE FOR A NAME THE ROUTINE DOES NOT TAKE: refused, and the only thing worth
	// saying is which name.
	said := saidOnStdout(t, func() {
		out, err = doAsProduct(t, d, "write a note",
			map[string]string{"message": "fine", "subject": secretish}, nil)
	})
	if err != nil {
		t.Fatalf("the refusal came back as an error: %v", err)
	}
	if out != OutcomeRefused {
		t.Fatalf("a value for an argument the play does not have came back %q", out)
	}
	// IT WAS SAID AT ALL, which is the half that makes the next assertion mean
	// something: a refusal nobody printed trivially does not repeat anything.
	if !strings.Contains(said, "subject") {
		t.Fatalf("the refusal does not name the argument: %q", said)
	}
	if strings.Contains(said, secretish) {
		t.Errorf("the refusal repeated the value: %q", said)
	}
}

// A SECRET CANNOT BE SUPPLIED THROUGH THE FLAG, THROUGH THE DOOR.
//
// One entrance may offer what another may not. A phrase carrying `password:value` has always
// reached the credential store and still does; a flag a window fills in and a command line carries
// must not become a second way to do that. `routes.CheckFlagged` is the rule and this is the
// wiring — which nothing else reaches, because the rule needs the source and the entrance needs to
// have been a flag.
func TestASecretGivenThroughTheFlagIsRefusedAtTheDoor(t *testing.T) {
	t.Setenv("MARCO_HOME", t.TempDir())
	t.Setenv("MARCO_NO_PANIC_STOP", "1")
	reg := routes.Registry{Dir: t.TempDir()}
	rt := routes.Route{App: "web", Slug: "log-in"}
	src := "use os.\n\nthe App is a script.\n\n" +
		"do OS's Secret with \"log-in:password\"...\n" +
		"    when ok?\n        log \"done\".\n    or?\n        log that's error.\n"
	if err := reg.Save(rt, src); err != nil {
		t.Fatal(err)
	}
	host := &recordHost{}
	d := orchestrator.Deps{Reg: reg, Hosts: map[string]runtime.Host{"*": host},
		In: strings.NewReader(""), Out: &strings.Builder{},
		App: func() string { return "web" }, Authority: allowGate{}}
	noDirector(t)
	var out Outcome
	var err error
	printed := saidOnStdout(t, func() {
		out, err = runInvocation(d, invoke.Request{
			Source: invoke.SourceCLI, Play: &rt,
			Named:   map[string]string{"password": "hunter2"},
			Flagged: []string{"password"},
		})
	})
	if err != nil {
		t.Fatalf("the refusal came back as an error: %v", err)
	}
	if out != OutcomeRefused {
		t.Fatalf("a secret given through a flag came back %q", out)
	}
	if len(host.pressed()) != 0 {
		t.Errorf("it pressed %v", host.pressed())
	}
	if !strings.Contains(printed, "credential store") {
		t.Errorf("the refusal does not say where the value comes from: %q", printed)
	}
	if strings.Contains(printed, "hunter2") {
		t.Errorf("the refusal repeated the value: %q", printed)
	}
	// AND THE PHRASE PATH IS UNTOUCHED: the same value, arriving as words, is not
	// refused by this rule. (It reaches `doSecret`, which is where it always went.)
	out, err = runInvocation(d, invoke.Request{
		Source: invoke.SourceCLI, Play: &rt,
		Named: map[string]string{"password": "hunter2"},
	})
	if err != nil || out == OutcomeRefused {
		t.Errorf("a secret arriving as words was refused by the flag's rule: %q / %v",
			out, err)
	}
}

// A SAVE BETWEEN THE CONFIRMATION AND THIS READ RUNS NOTHING.
//
// THE GAP THIS CLOSES, and it was open until it was pointed out. A surface reads the routine,
// shows somebody what it would type, takes their confirmation, and starts this process — which
// reads the file AGAIN. Studio's digest check happened before the spawn; the bytes that execute
// are read after it. A save landing in between ran a version nobody confirmed, WITH the values
// they supplied, which is the worst of it: the text was approved for other steps.
//
// So the confirmed version travels with the request and is compared against the one read this
// snapshot is made from — the same bytes `filled` is built out of and the same bytes that run.
// Asking the file a second time here would be a second answer about one file and would reopen the
// gap.
func TestASaveBetweenTheConfirmationAndTheReadRunsNothing(t *testing.T) {
	d, host := aRoutineThatTypesAValue(t)
	rt := routes.Route{App: "notepad", Slug: "write-a-note"}
	// WHAT A SURFACE WOULD HAVE CONFIRMED: the routine as it stood a moment ago.
	was, err := os.ReadFile(d.Reg.Path(rt))
	if err != nil {
		t.Fatal(err)
	}
	confirmed := routes.DigestOf(string(was))
	// AND THEN SOMETHING SAVES IT, after that check and before this read.
	if err := d.Reg.Replace(rt, string(was)+"\n// and a change nobody confirmed\n"); err != nil {
		t.Fatal(err)
	}
	noDirector(t)
	var out Outcome
	printed := saidOnStdout(t, func() {
		out, err = runInvocation(d, invoke.Request{
			Source: invoke.SourceCLI, Play: &rt,
			Named:  map[string]string{"message": "the text I approved"},
			Expect: confirmed,
		})
	})
	if err != nil {
		t.Fatalf("the refusal came back as an error: %v", err)
	}
	if out != OutcomeRefused {
		t.Fatalf("a version nobody confirmed came back %q", out)
	}
	// ZERO INPUT. Refused before `ApplyArgs` and before a reference is claimed, so
	// nothing was pressed and nothing was typed.
	if len(host.pressed()) != 0 {
		t.Errorf("it pressed %v", host.pressed())
	}
	if !strings.Contains(printed, "saved again") {
		t.Errorf("the refusal does not say what happened: %q", printed)
	}
	if strings.Contains(printed, "the text I approved") {
		t.Errorf("the refusal repeated the value: %q", printed)
	}
}

// AND THE SAME ROUTINE, UNCHANGED, RUNS WITH THE VERSION IT WAS CONFIRMED AGAINST.
//
// The control. A pin that refuses everything passes the case above, and a pin that is never
// consulted passes this one — so both are asserted, and the second one types the text.
func TestAConfirmedVersionThatStillMatchesRuns(t *testing.T) {
	d, host := aRoutineThatTypesAValue(t)
	rt := routes.Route{App: "notepad", Slug: "write-a-note"}
	was, err := os.ReadFile(d.Reg.Path(rt))
	if err != nil {
		t.Fatal(err)
	}
	noDirector(t)
	out, err := runInvocation(d, invoke.Request{
		Source: invoke.SourceCLI, Play: &rt,
		Named:  map[string]string{"message": "hello there"},
		Expect: routes.DigestOf(string(was)),
	})
	if err != nil {
		t.Fatalf("the run failed: %v", err)
	}
	if out != OutcomePerformed {
		t.Fatalf("a play that had not changed came back %q", out)
	}
	if got := typed(host); len(got) != 1 || got[0] != "hello there" {
		t.Errorf("it typed %q", got)
	}
}

// AND AN ENTRANCE THAT CONFIRMED NOTHING PINS NOTHING.
//
// Empty is unchanged behaviour rather than a hole: the CLI, a hotkey and the overlay pin no
// version because nothing was confirmed to them. What the pin closes is the gap between a
// confirmation and the run it authorised, and a pin that refused when absent would have broken
// every other entrance.
func TestAnEntranceThatConfirmedNothingPinsNothing(t *testing.T) {
	d, host := aRoutineThatTypesAValue(t)
	rt := routes.Route{App: "notepad", Slug: "write-a-note"}
	was, _ := os.ReadFile(d.Reg.Path(rt))
	if err := d.Reg.Replace(rt, string(was)+"\n// changed, and nobody confirmed anything\n"); err != nil {
		t.Fatal(err)
	}
	noDirector(t)
	out, err := runInvocation(d, invoke.Request{
		Source: invoke.SourceCLI, Play: &rt,
		Named: map[string]string{"message": "hello there"},
	})
	if err != nil {
		t.Fatalf("the run failed: %v", err)
	}
	if out != OutcomePerformed {
		t.Fatalf("an invocation that pinned no version came back %q", out)
	}
	if got := typed(host); len(got) != 1 {
		t.Errorf("it typed %q", got)
	}
}
