package main

// A SURFACE THAT CANNOT REVIEW A PROPOSAL SAYS SO, THROUGH THE ONE DOOR.
//
// A request can already say what to type, and Director reads which words those are — but a
// proposal is only useful where somebody can see it and correct it before anything is typed. The
// CLI, a hotkey and the overlay's command line have no field and no confirmation step, so for a
// routine that needs text and was given none they can run with a guess, fail quietly, or EXPLAIN.
//
// These are about the third, at the entrance somebody meets it on: `runInvocation`, which is what
// `marco do` and `marco hotkey` both reach. And about the two things that must NOT change — a
// value supplied explicitly still runs, and a routine that takes nothing is an ordinary routine.
//
// See [[ADR-277-a-request-may-propose-the-text-a-routine-types]].

import (
	"os"
	"strings"
	"testing"

	"github.com/chaynes-simpleclouds/marco/internal/invoke"
	"github.com/chaynes-simpleclouds/marco/internal/orchestrator"
	"github.com/chaynes-simpleclouds/marco/internal/routes"
	"github.com/chaynes-simpleclouds/marco/internal/runtime"
)

// theReviewSentence is the actionable half, as a person reads it.
const theReviewSentence = "This request needs text values reviewed before running. " +
	"Open it in Studio"

// sentToStudio is whether the output carries the clause that sends somebody to review it.
//
// THE SENTENCE, NOT THE WORD. A run record's path runs through the temp directory, which carries
// the TEST'S OWN NAME — so a test named ...IsNotSentToStudio matched the word in its own path and
// failed for a reason that had nothing to do with what was printed. The first version of these
// did exactly that.
func sentToStudio(said string) bool {
	return strings.Contains(said, theReviewSentence)
}

// doAsProductExpecting is `doAsProduct` for an entrance that CONFIRMED a version.
//
// Studio's shape: it reads the routine, shows what it would type, takes a confirmation and then
// starts a child that reads the file again — so the version travels. An empty one is every
// entrance that confirmed nothing, which is the condition this file is about.
func doAsProductExpecting(t *testing.T, d orchestrator.Deps, text string,
	named map[string]string, expect string) (Outcome, error) {

	t.Helper()
	noDirector(t)
	return runInvocation(d, invoke.Request{
		Text: text, Source: invoke.SourceCLI, Named: named, Expect: expect,
	})
}

// aRoutineThatTakesNothing is a saved routine with no arguments at all.
func aRoutineThatTakesNothing(t *testing.T) (orchestrator.Deps, *recordHost) {
	t.Helper()
	t.Setenv("MARCO_HOME", t.TempDir())
	t.Setenv("MARCO_NO_PANIC_STOP", "1")
	reg := routes.Registry{Dir: t.TempDir()}
	rt := routes.Route{App: "notepad", Slug: "open-settings"}
	src := "// Auto-generated by `marco learn \"open settings\"`.\n" +
		"use os.\n\nthe App is a script.\n\n" +
		"do OS's Key with \"ctrl+comma\"...\n" +
		"    when ok?\n        log \"done\".\n    or?\n        log that's error.\n"
	if err := reg.Save(rt, src); err != nil {
		t.Fatal(err)
	}
	host := &recordHost{}
	return orchestrator.Deps{
		Reg:       reg,
		Hosts:     map[string]runtime.Host{"*": host},
		In:        strings.NewReader(""),
		Out:       &strings.Builder{},
		App:       func() string { return "notepad" },
		Authority: allowGate{},
	}, host
}

// ASKED FOR IN WORDS ALONE, A ROUTINE THAT NEEDS TEXT IS EXPLAINED AND NOT RUN.
func TestASurfaceWithNoReviewSaysWhereToReviewIt(t *testing.T) {
	d, host := aRoutineThatTypesAValue(t)
	var out Outcome
	var err error
	said := saidOnStdout(t, func() {
		out, err = doAsProduct(t, d, "write a note", nil, nil)
	})
	if err != nil {
		t.Fatalf("the refusal came back as an error: %v", err)
	}
	if out != OutcomeRefused {
		t.Errorf("the invocation came back %q, not refused", out)
	}
	// NOTHING EXECUTED. The explanation is instead of the run, not beside it.
	if len(host.pressed()) != 0 {
		t.Errorf("it pressed %v", host.pressed())
	}
	if len(typed(host)) != 0 {
		t.Errorf("it typed %v", typed(host))
	}
	// AND THE EXPLANATION IS ACTIONABLE: which argument, and what to do about it.
	if !strings.Contains(said, theReviewSentence) {
		t.Errorf("the refusal does not say where to review it: %q", said)
	}
	if !strings.Contains(said, "message") {
		t.Errorf("the refusal does not name the argument: %q", said)
	}
	if !strings.Contains(said, "supply the value with the request") {
		t.Errorf("the refusal does not offer the other way: %q", said)
	}
}

// AND THE WHOLE SENTENCE, EXACTLY, BECAUSE ANOTHER MODULE HOLDS A COPY OF IT.
//
// `plugins/overlay` is a separate module and cannot import this one, so its test for "the
// explanation reaches the HUD" carries the sentence as a literal. A copy that drifts is the known
// cost of that, and this is what pays it: the door's own words, asserted here, so a reworded
// refusal fails in the module that changed it rather than going quiet in the one that did not.
//
// If this fails, `theEngineRefusal` in `plugins/overlay/valuesneeded_test.go` is the other half to
// update.
func TestTheEngineStillSaysWhatThisExpects(t *testing.T) {
	d, _ := aRoutineThatTypesAValue(t)
	said := saidOnStdout(t, func() {
		if out, err := doAsProduct(t, d, "write a note", nil, nil); err != nil ||
			out != OutcomeRefused {
			t.Fatalf("the invocation came back %q (%v)", out, err)
		}
	})
	const want = `"write a note": this routine types text that has to be supplied, ` +
		`and no value was given for "message". This request needs text values ` +
		`reviewed before running. Open it in Studio, or supply the value with the ` +
		`request`
	if !strings.Contains(said, want) {
		t.Errorf("the door says %q and the overlay's copy expects %q", said, want)
	}
}

// AND THE CLAUSE BELONGS TO ONE REFUSAL, NOT TO EVERY REFUSAL ABOUT ARGUMENTS.
//
// `CheckArgs` says four different things, and only one of them has an answer that depends on where
// the request came from. The other three are wrong at every entrance — a name the routine does not
// take is a name it does not take, in Studio as much as in a terminal — and sending somebody to
// REVIEW TEXT when they have misspelt an argument, pasted a line break, or given more values than
// the routine has places for is sending them to look at the wrong thing entirely.
//
// Which is why the refusal is recognised by its TYPE and not by being a refusal. A mutation that
// dropped the type check and kept only the confirmation gate survived everything else here.
func TestOnlyAMissingValueIsSentToStudio(t *testing.T) {
	for _, c := range []struct {
		why        string
		named      map[string]string
		positional []string
		says       string
	}{
		{"a misspelt argument", map[string]string{"mesage": "x"}, nil,
			"does not take"},
		{"a value with a line break in it",
			map[string]string{"message": "first\nsecond"}, nil,
			"more than one line"},
		{"more values than the routine has places for", nil,
			[]string{"one", "two"}, "values were given"},
	} {
		d, host := aRoutineThatTypesAValue(t)
		var out Outcome
		var err error
		said := saidOnStdout(t, func() {
			out, err = doAsProduct(t, d, "write a note", c.named, c.positional)
		})
		if err != nil {
			t.Fatalf("%s came back as an error: %v", c.why, err)
		}
		// STILL REFUSED, AND STILL FOR ITS OWN REASON.
		if out != OutcomeRefused {
			t.Errorf("%s came back %q", c.why, out)
		}
		if len(host.pressed()) != 0 || len(typed(host)) != 0 {
			t.Errorf("%s pressed %v and typed %v", c.why, host.pressed(),
				typed(host))
		}
		if !strings.Contains(said, c.says) {
			t.Errorf("%s was refused as %q, want it to say %q", c.why, said,
				c.says)
		}
		// AND NOT TOLD TO GO AND REVIEW TEXT.
		if sentToStudio(said) {
			t.Errorf("%s was sent to Studio: %q", c.why, said)
		}
	}
}

// AND A VALUE SUPPLIED EXPLICITLY STILL RUNS, WITH NOTHING SAID ABOUT REVIEWING IT.
//
// The first thing that must not change. A script, a binding that carries its own text and
// `marco do --arg=` are all somebody having already said what to type, and sending them to Studio
// would be sending them to review a decision they have made.
func TestAnExplicitlySuppliedValueStillRunsAndIsNotSentToStudio(t *testing.T) {
	d, host := aRoutineThatTypesAValue(t)
	var out Outcome
	var err error
	said := saidOnStdout(t, func() {
		out, err = doAsProduct(t, d, "write a note",
			map[string]string{"message": "hello there"}, nil)
	})
	if err != nil {
		t.Fatalf("the run failed: %v", err)
	}
	if out != OutcomePerformed {
		t.Fatalf("the invocation came back %q", out)
	}
	if got := typed(host); len(got) != 1 || got[0] != "hello there" {
		t.Errorf("it typed %q", got)
	}
	if sentToStudio(said) {
		t.Errorf("a supplied value was sent to Studio anyway: %q", said)
	}
}

// AND A POSITIONAL VALUE IS A SUPPLIED VALUE TOO.
func TestAPositionalValueStillRuns(t *testing.T) {
	d, host := aRoutineThatTypesAValue(t)
	said := saidOnStdout(t, func() {
		if out, err := doAsProduct(t, d, "write a note", nil,
			[]string{"hello there"}); err != nil || out != OutcomePerformed {
			t.Errorf("the invocation came back %q (%v)", out, err)
		}
	})
	if got := typed(host); len(got) != 1 || got[0] != "hello there" {
		t.Errorf("it typed %q", got)
	}
	if sentToStudio(said) {
		t.Errorf("a positional value was sent to Studio: %q", said)
	}
}

// AND AN ORDINARY ROUTINE THAT TAKES NOTHING IS AN ORDINARY ROUTINE.
//
// The second thing that must not change, and the common case: every routine saved before any of
// this existed takes no arguments, and none of them may acquire a sentence about reviewing text.
func TestARoutineThatTakesNothingRunsWithNothingSaidAboutReviewing(t *testing.T) {
	d, host := aRoutineThatTakesNothing(t)
	var out Outcome
	var err error
	said := saidOnStdout(t, func() {
		out, err = doAsProduct(t, d, "open settings", nil, nil)
	})
	if err != nil {
		t.Fatalf("the run failed: %v", err)
	}
	if out != OutcomePerformed {
		t.Fatalf("the invocation came back %q", out)
	}
	if len(host.pressed()) == 0 {
		t.Error("it pressed nothing")
	}
	if sentToStudio(said) || strings.Contains(said, "reviewed") {
		t.Errorf("a routine that takes nothing was told to review text: %q", said)
	}
}

// AND A REQUEST SOMETHING ALREADY CONFIRMED IS NEVER SENT TO STUDIO.
//
// Because it may have come FROM Studio. An entrance that pinned a version is one that showed
// somebody what the routine would type and took an answer, so telling it to go and do that is
// telling it to do what it just did. The condition is read off the request — the digest it was
// authorised against — rather than off a list of surface names that would have to be kept right.
func TestAConfirmedRequestIsNotToldToOpenStudio(t *testing.T) {
	d, host := aRoutineThatTypesAValue(t)
	// THE ROUTINE AS IT STANDS, so the version check PASSES and the argument rules are
	// what answers. A digest that did not match would refuse one step earlier, for a
	// different reason, and prove nothing about this one.
	rt := routes.Route{App: "notepad", Slug: "write-a-note"}
	src, err := os.ReadFile(d.Reg.Path(rt))
	if err != nil {
		t.Fatal(err)
	}
	var out Outcome
	said := saidOnStdout(t, func() {
		out, err = doAsProductExpecting(t, d, "write a note", nil,
			routes.DigestOf(string(src)))
	})
	if err != nil {
		t.Fatalf("the refusal came back as an error: %v", err)
	}
	if len(host.pressed()) != 0 {
		t.Errorf("it pressed %v", host.pressed())
	}
	if out != OutcomeRefused {
		t.Fatalf("a missing value was not refused: %q", out)
	}
	// STILL REFUSED, AND STILL NAMING THE ARGUMENT — only the clause about where to review
	// it is absent, because something already did.
	if !strings.Contains(said, "message") {
		t.Errorf("the refusal does not name the argument: %q", said)
	}
	if sentToStudio(said) {
		t.Errorf("a confirmed request was told to open Studio: %q", said)
	}
}
