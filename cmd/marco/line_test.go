package main

// S6 AT THE ENGINE: what the widget's command line would run, read back before Enter. Entered
// through readLine (the whole of `marco line`) over a registry of the test's own, and what a
// reading becomes is then run through parseDoArgs and the door with a recording host, so the
// read-back and the run are held together rather than each checked alone.

import (
	"os"
	"sort"
	"strings"
	"testing"

	"github.com/chaynes-simpleclouds/marco/internal/orchestrator"
	"github.com/chaynes-simpleclouds/marco/internal/routes"
	"github.com/chaynes-simpleclouds/marco/internal/runtime"
)

// typesSrc is a routine that types its arguments, in the order given.
func typesSrc(name string, args ...string) string {
	src := "// Auto-generated by `marco learn \"" + name + "\"`.\nuse os.\n\nthe App is a script.\n\n"
	for _, a := range args {
		src += "do OS's Type with \"{{" + a + "}}\"...\n    when ok?\n        log \"typed\".\n" +
			"    or?\n        log that's error.\n"
	}
	return src
}

// aLineWorld is a library with argument routines in game-b and one in notepad, a recording host,
// and a door that says yes, so nothing but the reading and the argument rules decides anything.
func aLineWorld(t *testing.T) (orchestrator.Deps, *recordHost) {
	t.Helper()
	t.Setenv("MARCO_HOME", t.TempDir())
	t.Setenv("MARCO_NO_PANIC_STOP", "1")
	reg := routes.Registry{Dir: t.TempDir()}
	for rt, src := range map[routes.Route]string{
		{App: "game-b", Slug: "cloud-pull"}:       typesSrc("cloud pull", "resource"),
		{App: "game-b", Slug: "cloud-pull-stone"}: typesSrc("cloud pull stone"),
		{App: "notepad", Slug: "greet"}:           typesSrc("greet", "name", "message"),
		{Slug: "log-in"}: typesSrc("log in", "user") +
			"do OS's Secret with \"log-in:password\".\n",
	} {
		if err := reg.Save(rt, src); err != nil {
			t.Fatal(err)
		}
	}
	host := &recordHost{}
	return orchestrator.Deps{Reg: reg, Hosts: map[string]runtime.Host{"*": host},
		In: strings.NewReader(""), Out: &strings.Builder{},
		App: func() string { return "game-b" }, Authority: allowGate{}}, host
}

// runReading performs what the widget sends for a runnable reading, through the entrance's own
// argument parser and the door, and returns what the host typed.
func runReading(t *testing.T, d orchestrator.Deps, host *recordHost, r lineReading) []string {
	t.Helper()
	args := []string{"--source=typed", "--play=" + r.Slug, "--app=" + r.App, "--expect=" + r.SourceAt}
	if r.App == "" {
		args = []string{"--source=typed", "--play=" + r.Slug, "--expect=" + r.SourceAt}
	}
	keys := make([]string, 0, len(r.Values))
	for k := range r.Values {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, k := range keys {
		args = append(args, "--arg="+k+"="+r.Values[k])
	}
	req, _, _, err := parseDoArgs(args)
	if err != nil {
		t.Fatal(err)
	}
	host.calls = nil
	if _, err := captureStdout(t, func() error { doOrExplain(d, req, false); return nil }); err != nil {
		t.Fatal(err)
	}
	return typed(host)
}

// The three agreed forms are ONE reading: the same identity, the same version, the same value,
// and running it types that value. No model is asked: nothing here has a resolver.
func TestTheThreeFormsAreOneInvocation(t *testing.T) {
	d, host := aLineWorld(t)
	var first lineReading
	for i, line := range []string{"cloud pull granite", "cloud pull with granite", "cloud pull resource:granite"} {
		r := readLine(d, "game-b", line, lineProposal{})
		if r.Kind != "routine" || !r.Runnable || r.ID != (routes.Route{App: "game-b", Slug: "cloud-pull"}).ID() || r.Values["resource"] != "granite" {
			t.Fatalf("%q reads as %+v", line, r)
		}
		if r.Readback != "Cloud pull · resource: granite" {
			t.Errorf("%q reads back as %q", line, r.Readback)
		}
		if i == 0 {
			first = r
		} else if r.SourceAt != first.SourceAt || r.ID != first.ID {
			t.Errorf("%q is a different identity or version from %q", line, "cloud pull granite")
		}
		if got := runReading(t, d, host, r); len(got) != 1 || got[0] != "granite" {
			t.Errorf("%q typed %q", line, got)
		}
	}
	// A value of several words is the rest of the line as typed.
	if r := readLine(d, "game-b", "cloud pull  river  stone", lineProposal{}); r.Values["resource"] != "river  stone" {
		t.Errorf("a value of several words reads as %q", r.Values["resource"])
	}
}

// An exact routine name wins: `cloud pull stone` is the routine of that name, with no values, and
// never `cloud pull` with `stone`.
//
// Deleting the exact step must fail this.
func TestAnExactNameWinsOverATemplate(t *testing.T) {
	d, _ := aLineWorld(t)
	r := readLine(d, "game-b", "cloud pull stone", lineProposal{})
	if r.ID != (routes.Route{App: "game-b", Slug: "cloud-pull-stone"}).ID() || r.Form != "exact" || len(r.Values) != 0 || r.Needs {
		t.Errorf("the line read as %+v", r)
	}
}

// A routine named with nothing after it says what it needs and runs nothing; so does Enter on it.
func TestAMissingValueIsAskedFor(t *testing.T) {
	d, _ := aLineWorld(t)
	r := readLine(d, "game-b", "cloud pull", lineProposal{})
	if r.Runnable || r.Pending != "‹resource›" || r.Says != "Resource needed · cloud pull ‹resource›" {
		t.Errorf("a routine with its value missing reads as %+v", r)
	}
	g := readLine(d, "notepad", "greet name:sam", lineProposal{})
	if g.Runnable || g.Pending != "message:‹message›" || !strings.HasPrefix(g.Says, "Message needed") {
		t.Errorf("one of two values missing reads as %+v", g)
	}
}

// Two values with no labels are asked about, never guessed; named, each runs to the next label.
func TestSeveralValuesWithoutLabelsAreAskedAbout(t *testing.T) {
	d, host := aLineWorld(t)
	r := readLine(d, "notepad", "greet sam see you at 8", lineProposal{})
	if r.Runnable || r.Says != "Two values needed — say which: greet name:‹name› message:‹message›" {
		t.Errorf("an unlabelled line for a two-value routine reads as %+v", r)
	}
	n := readLine(d, "notepad", "greet name:sam message:see you at 8", lineProposal{})
	if !n.Runnable || n.Readback != "Greet · name: sam · message: see you at 8" {
		t.Fatalf("the named line reads as %+v", n)
	}
	d.App = func() string { return "notepad" }
	if got := runReading(t, d, host, n); strings.Join(got, "|") != "sam|see you at 8" {
		t.Errorf("the named line typed %q", got)
	}
}

// A value the credential store answers is never typed on this line, and is said as where it
// comes from.
func TestASecretIsNeitherAskedForNorTyped(t *testing.T) {
	d, _ := aLineWorld(t)
	r := readLine(d, "game-b", "log in sam", lineProposal{})
	if !r.Runnable || r.Values["user"] != "sam" || r.Readback != "Log in · user: sam · password: from the credential store" {
		t.Errorf("a routine with a secret reads as %+v", r)
	}
	if _, carried := r.Values["password"]; carried {
		t.Error("a secret was carried as a value")
	}
}

// A line that names nothing goes to the intake as words, as it always has.
func TestALineThatNamesNothingIsLeftToTheIntake(t *testing.T) {
	d, _ := aLineWorld(t)
	for _, line := range []string{"pull some stone down from the cloud", "cloud", "greet with", "make coffee name:x"} {
		if r := readLine(d, "game-b", line, lineProposal{}); r.Kind != "none" && line != "greet with" {
			t.Errorf("%q reads as %+v", line, r)
		}
	}
	// A routine in another application is not named from here.
	if r := readLine(d, "game-b", "greet name:sam message:hi", lineProposal{}); r.Kind != "none" {
		t.Errorf("notepad's greet read from game-b: %+v", r)
	}
}

// What Director proposed is labelled as that until the person changes it, and theirs after; a
// proposal for an earlier revision refuses; a line that names another routine drops it.
func TestAProposalIsReviewedNotSupplied(t *testing.T) {
	d, host := aLineWorld(t)
	rt := routes.Route{App: "game-b", Slug: "cloud-pull"}
	at := readLine(d, "game-b", "cloud pull", lineProposal{}).SourceAt
	p := lineProposal{Route: rt, Carrying: true, Values: map[string]string{"resource": "stone"}, At: at}

	kept := readLine(d, "game-b", "cloud pull resource:stone", p)
	if !kept.Runnable || kept.From["resource"] != routes.FromExtracted ||
		kept.Readback != "Cloud pull · resource: stone (read out of what you said)" {
		t.Errorf("a proposal left alone reads as %+v", kept)
	}
	edited := readLine(d, "game-b", "cloud pull resource:granite", p)
	if edited.From["resource"] != routes.FromEdited ||
		edited.Readback != "Cloud pull · resource: granite (as you corrected it)" {
		t.Errorf("a corrected proposal reads as %+v", edited)
	}
	if got := runReading(t, d, host, edited); len(got) != 1 || got[0] != "granite" {
		t.Errorf("the corrected proposal typed %q", got)
	}
	other := readLine(d, "game-b", "cloud pull stone", p)
	if other.ID == rt.ID() {
		t.Fatalf("the exact routine lost to the proposal: %+v", other)
	}
	if other.Runnable || !strings.Contains(other.Says, "the routine those values were proposed for") {
		t.Errorf("a line naming another routine with a proposal carried reads as %+v", other)
	}

	// Saved since the proposal was read: refused, even with the same names.
	if err := d.Reg.Save(rt, typesSrc("cloud pull", "resource")+"log \"changed\".\n"); err != nil {
		t.Fatal(err)
	}
	stale := readLine(d, "game-b", "cloud pull resource:stone", p)
	if stale.Runnable || !strings.Contains(stale.Says, "saved again since those values were read") {
		t.Errorf("a proposal for an earlier revision reads as %+v", stale)
	}
}

// THE VERSION SHOWN IS THE VERSION RUN: a routine saved between the read-back and Enter is
// refused at the door, and types nothing.
func TestARoutineSavedAfterTheReadBackIsRefused(t *testing.T) {
	d, host := aLineWorld(t)
	r := readLine(d, "game-b", "cloud pull stone2", lineProposal{})
	if !r.Runnable {
		t.Fatalf("%+v", r)
	}
	rt := routes.Route{App: "game-b", Slug: "cloud-pull"}
	if err := d.Reg.Save(rt, typesSrc("cloud pull", "resource")+"log \"changed\".\n"); err != nil {
		t.Fatal(err)
	}
	if got := runReading(t, d, host, r); len(got) != 0 {
		t.Errorf("a routine saved after its read-back typed %q", got)
	}
}

// The arguments are read as given: everything after `--` is the line, so nothing typed is a flag.
func TestTheLineIsReadAfterItsFlags(t *testing.T) {
	line, p, ok := lineArgs([]string{"--json", "--play=cloud pull", "--app=game-b", "--proposed=Resource=a=b",
		"--proposed-at=x", "--", "cloud", "pull", "--focus"})
	if !ok || line != "cloud pull --focus" || p.Route.Slug != "cloud-pull" || p.Route.App != "game-b" ||
		p.Route.Focus || p.Values["resource"] != "a=b" || p.At != "x" || !p.Carrying {
		t.Errorf("read as %q %+v %v", line, p, ok)
	}
	if _, _, ok := lineArgs([]string{"--json", "cloud pull"}); ok {
		t.Error("a line with no -- was accepted")
	}
	_ = os.Getenv
}

// A value given in order that would land on a value the credential store answers is refused, not
// typed and not dropped. (The routine's order puts its secrets after the text it types, so it is
// the value one too many.)
func TestAValueInOrderNeverLandsOnASecret(t *testing.T) {
	d, _ := aLineWorld(t)
	r := readLine(d, "game-b", "log in with sam, hunter2", lineProposal{})
	if r.Runnable || !strings.Contains(r.Says, "credential store") || strings.Contains(r.Says, "hunter2") {
		t.Errorf("a value in order for a secret reads as %+v", r)
	}
}

// The bare form is a routine THAT TAKES A VALUE followed by it: a longer name that takes none does
// not capture the line, and a line with a label in it that names nothing is not read as words
// after a routine (the label would become part of the value).
func TestTheBareFormIsARoutineThatTakesAValue(t *testing.T) {
	d, _ := aLineWorld(t)
	if r := readLine(d, "game-b", "cloud pull stone granite", lineProposal{}); r.Slug != "cloud-pull" ||
		r.Values["resource"] != "stone granite" {
		t.Errorf("a line past a routine that takes no value reads as %+v", r)
	}
	if r := readLine(d, "game-b", "cloud pull now resource:stone", lineProposal{}); r.Kind != "none" {
		t.Errorf("a labelled line naming nothing reads as %+v", r)
	}
}

// A context routine and a focus routine share the application and the name. A line read with the
// proposals Director made for the FOCUS one resolves to the context one, and is refused, never
// read as that routine with the proposals dropped and the values looking typed.
//
// Dropping the proposals silently must fail this.
func TestAProposalForAFocusRoutineIsNotReadOnItsNamesake(t *testing.T) {
	d, _ := aLineWorld(t)
	focus := routes.Route{App: "game-b", Focus: true, Slug: "cloud-pull"}
	if err := d.Reg.Save(focus, typesSrc("cloud pull", "resource")); err != nil {
		t.Fatal(err)
	}
	at := routes.DigestOf(typesSrc("cloud pull", "resource"))
	p := lineProposal{Route: focus, Carrying: true, Values: map[string]string{"resource": "stone"}, At: at}
	r := readLine(d, "game-b", "cloud pull resource:stone", p)
	if r.ID == focus.ID() {
		t.Fatalf("the fixture did not produce the namesake: %+v", r)
	}
	if r.Runnable || r.From["resource"] == routes.FromTyped || !strings.Contains(r.Says, focus.ID()) {
		t.Errorf("a proposal for the focus routine read on its namesake: %+v", r)
	}
}
