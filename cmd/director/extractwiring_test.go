package main

// DIRECTOR'S OWN HANDLER REACHES THE REAL EXTRACTION QUESTION.
//
// Prove wiring by deleting it: `Extract: resolver.Extract` is a single line in
// `ResolveRoute`, and every other test in this package hands the policy a stand-in. A stand-in
// establishes the policy and NOTHING about whether the production path reaches the thing the
// policy calls — which is the defect this repository keeps finding, and the reason the resolver
// sat complete and unreached for a release.
//
// So this goes through `Runtime.ResolveRoute`, Director's own handler, with a real plugin
// executable on `$MARCO_RESOLVER`: a plugin this test builds, not a model. What it establishes is
// that a request leaving Director arrives at a plugin and that the spans it answers with become
// values. Whether a MODEL reads sentences well is a different question, is not asked here, and is
// behind `-tags resolver`.
//
// See [[Extracting-argument-values-proposal-2026-10-30]].

import (
	"os"
	"os/exec"
	"path/filepath"
	"runtime"
	"strings"
	"testing"

	"github.com/chaynes-simpleclouds/marco/internal/director/service"
	"github.com/chaynes-simpleclouds/marco/internal/routes"
)

// answeringBothQuestions is a plugin that answers the route question and the extraction question
// with one fixed reply.
//
// ONE REPLY FOR BOTH, which works because each question reads its own fields: the route question
// reads `intent` and `route` and the extraction question reads `values`, and a field neither
// asked about is simply not read. That is the whole of why a third question could be added to
// this protocol without every existing plugin having to know about it.
//
// The route half needs the `intent`, because `dispatch.PluginAdvisor` refuses a reply without
// one — which is what a real plugin's converse mode sends.
const answeringBothQuestions = `package main

import (
	"bufio"
	"fmt"
	"os"
)

func main() {
	_, _ = bufio.NewReader(os.Stdin).ReadString('\n')
	fmt.Println(` + "`" + `{"intent":"run","route":"write-a-note",` +
	`"values":[{"name":"message","start":20,"end":31}]}` + "`" + `)
}
`

// aPluginHere builds a one-file plugin and returns its path.
func aPluginHere(t *testing.T, source string) string {
	t.Helper()
	dir := t.TempDir()
	if err := os.WriteFile(filepath.Join(dir, "main.go"), []byte(source), 0o644); err != nil {
		t.Fatal(err)
	}
	bin := filepath.Join(dir, "plugin")
	if runtime.GOOS == "windows" {
		bin += ".exe"
	}
	cmd := exec.Command("go", "build", "-o", bin, "main.go")
	cmd.Dir = dir
	if out, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("building the plugin: %v\n%s", err, out)
	}
	return bin
}

// aRoutineThatTakesText writes one routine that types a supplied value, and returns its library.
func aRoutineThatTakesText(t *testing.T) routes.Registry {
	t.Helper()
	dir := t.TempDir()
	t.Setenv("MARCO_ROUTES", dir)
	reg := routes.Registry{Dir: dir}
	rt := routes.Route{App: "notepad", Focus: true, Slug: "write-a-note"}
	src := "// Auto-generated by `marco learn \"write-a-note\"`.\n" +
		"// Generation: 1.\nuse os.\n\nthe A is an actor.\n\n" +
		"this can Run.\nthis's Run does...\n" +
		"    do OS's Type with \"{{message}}\".\n" +
		"    when ok?\n        log \"typed\".\n    or?\n        log that's error.\n" +
		"    this is ok!\n\nthe App is a script.\n\ndo A's Run...\n" +
		"    when ok?\n        log \"done\".\n    or?\n        log that's error.\n"
	if err := reg.Save(rt, src); err != nil {
		t.Fatal(err)
	}
	return reg
}

// THE REQUEST LEAVES DIRECTOR, REACHES A PLUGIN, AND ITS SPANS COME BACK AS VALUES.
func TestDirectorsOwnHandlerReachesTheExtractionQuestion(t *testing.T) {
	plugin := aPluginHere(t, answeringBothQuestions)
	t.Setenv("MARCO_ASSISTANT", plugin)
	t.Setenv("MARCO_RESOLVER", plugin)
	reg := aRoutineThatTakesText(t)

	// "hello there" is [20, 31) in this request, which is what the plugin above names.
	const asked = "write a note saying hello there"
	r := &Runtime{}
	out := r.ResolveRoute(service.ResolveRoutePayload{
		Request: asked, Target: "notepad", Library: reg.Dir})

	if out.Mismatch != "" {
		t.Fatalf("the libraries disagreed: %s", out.Mismatch)
	}
	a := out.Answer
	if a.Kind != "run" || a.ID != "notepad/focus/write-a-note" {
		t.Fatalf("the plugin's route was not taken: %+v", a)
	}
	if len(a.Values) != 1 {
		t.Fatalf("the plugin's spans did not become values: %+v", a.Values)
	}
	got := a.Values[0]
	if got.Name != "message" || got.Value != "hello there" || got.From != "extracted" {
		t.Errorf("the proposal arrived as %+v", got)
	}
	// AND THE REVISION THE NAMES WERE READ FROM, which is what lets a confirmation refuse
	// a routine that was saved again under it.
	if a.SourceAt == "" {
		t.Error("the answer names no revision, so a proposal could outlive its names")
	}
	// AND THE VALUE IS THE REQUEST'S OWN WORDS. The plugin sent offsets and nothing else,
	// so this is Marco's copy of the sentence being read, not the plugin's.
	if !strings.Contains(asked, got.Value) {
		t.Errorf("%q is not in the request that was asked about", got.Value)
	}
}

// AND WITH NO PLUGIN THE SAME REQUEST SELECTS NOTHING TO PROPOSE FOR.
//
// The other half of the wiring claim: the values above came from the plugin and not from
// somewhere in Director that would have produced them anyway.
func TestWithNoPluginDirectorProposesNothing(t *testing.T) {
	t.Setenv("MARCO_ASSISTANT", "")
	t.Setenv("MARCO_RESOLVER", "")
	reg := aRoutineThatTakesText(t)

	r := &Runtime{}
	a := r.ResolveRoute(service.ResolveRoutePayload{
		Request: "write a note saying hello there", Target: "notepad",
		Library: reg.Dir}).Answer

	if len(a.Values) != 0 || a.SourceAt != "" {
		t.Errorf("with no plugin the answer carries %+v at %q", a.Values, a.SourceAt)
	}
}
