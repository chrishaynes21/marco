// aLibraryHere writes two routines into a temporary library and points this process at it.
//
// By hand rather than through a recording, because what is under test is the READING: which
// routines Director offers, under which context, out of which library. A draft pipeline here
// would be testing the saver.
func aLibraryHere(t *testing.T) routes.Registry {
	t.Helper()
	dir := t.TempDir()
	t.Setenv("MARCO_ROUTES", dir)
	reg := routes.Registry{Dir: dir}
	for _, rt := range []routes.Route{
		{App: "arkascended", Focus: true, Slug: "ark-graphics"},
		{App: "arkascended", Slug: "ark-sound"},
		{Slug: "quit-everything"},
	} {
		src := "// Auto-generated by `marco learn \"" + rt.Slug + "\"`.\n" +
			"// Generation: 1.\nuse os.\n\nthe A is an actor.\n\n" +
			"this can Run.\nthis's Run does...\n    do OS's Key with \"a\".\n" +
			"    this is ok!\n\nthe App is a script.\n\ndo A's Run...\n" +
			"    when ok?\n        log \"done\".\n    or?\n        log that's error.\n"
		if err := reg.Save(rt, src); err != nil {
			t.Fatal(err)
		}
	}
	if marcopaths.Routes() != dir {
		t.Fatalf("this process reads %s and the fixture wrote %s", marcopaths.Routes(), dir)
	}
	return reg
}

// AND THE LIBRARY IS DIRECTOR'S, READ THROUGH THE SAME TWO READERS EVERYTHING ELSE USES.
func TestTheLibraryDirectorOffersIsItsOwn(t *testing.T) {
	reg := aLibraryHere(t)
	cs := theLibrary(reg)
	if len(cs) != 3 {
		t.Fatalf("the library offered %d routine(s), want the three written: %+v",
			len(cs), cs)
	}
	ids := map[string]resolveroute.Candidate{}
	for _, c := range cs {
		ids[c.ID] = c
	}
	for _, want := range []string{"arkascended/focus/ark-graphics",
		"arkascended/context/ark-sound", "global/quit-everything"} {
		c, ok := ids[want]
		if !ok {
			t.Fatalf("%s is not offered: %+v", want, cs)
		}
		if !c.Runnable {
			t.Errorf("%s is offered as unrunnable, and nothing in it refuses", want)
		}
		if c.ID != orchestrator.RouteID(c.Route) {
			t.Errorf("%s carries an identity that is not its route's", want)
		}
	}
	// AND THE SCOPE EACH ONE IS ALREADY UNDER, read off where it lives rather than guessed.
	if got := ids["arkascended/focus/ark-graphics"].Scope; got != "app-anywhere" {
		t.Errorf("the focus routine's scope is %q", got)
	}
	if got := ids["global/quit-everything"].Scope; got != "everywhere" {
		t.Errorf("the global routine's scope is %q", got)
	}
}

// AND IT REPORTS WHAT EACH ROUTINE TAKES, WITH THE REVISION IT READ THEM FROM.
//
// The names a value may be proposed for, and the version those names came from. Both off the SAME
// read as the routine's name, so a routine saved between two reads cannot contribute its names to
// one and its digest to the other — and a proposal prepared against one revision can be refused
// rather than crossed into a routine it was never prepared for.
//
// A SECRET IS STILL REPORTED HERE, and is reported as a secret. What must never happen is asking
// a model about it, and that is `resolveroute`'s rule: this is the library saying truthfully what
// the routine declares, which is also how a surface knows to send somebody to the credential
// store instead of to a text box.
func TestTheLibrarySaysWhatEachRoutineTakes(t *testing.T) {
	dir := t.TempDir()
	t.Setenv("MARCO_ROUTES", dir)
	reg := routes.Registry{Dir: dir}
	rt := routes.Route{App: "notepad", Focus: true, Slug: "write-a-note"}
	src := "// Auto-generated by `marco learn \"write-a-note\"`.\n" +
		"// Generation: 1.\nuse os.\n\nthe A is an actor.\n\n" +
		"this can Run.\nthis's Run does...\n" +
		"    do OS's Type with \"{{message}}\".\n" +
		"    when ok?\n        do OS's Secret with \"write-a-note:token\".\n" +
		"    or?\n        log that's error.\n    this is ok!\n\n" +
		"the App is a script.\n\ndo A's Run...\n" +
		"    when ok?\n        log \"done\".\n    or?\n        log that's error.\n"
	if err := reg.Save(rt, src); err != nil {
		t.Fatal(err)
	}

	var got resolveroute.Candidate
	for _, c := range theLibrary(reg) {
		if c.ID == "notepad/focus/write-a-note" {
			got = c
		}
	}
	if got.ID == "" {
		t.Fatalf("the routine was not offered: %+v", theLibrary(reg))
	}
	// THE TEXT ARGUMENT AND THE SECRET, each said for what it is.
	if len(got.Takes) != 2 {
		t.Fatalf("it reports taking %+v", got.Takes)
	}
	if got.Takes[0] != (routes.Argument{Name: "message"}) {
		t.Errorf("the text argument is reported as %+v", got.Takes[0])
	}
	if got.Takes[1] != (routes.Argument{Name: "token", Secret: true}) {
		t.Errorf("the secret is reported as %+v", got.Takes[1])
	}
	// AND THE REVISION IS THE DIGEST OF THE BYTES THOSE NAMES WERE READ FROM.
	if want := routes.DigestOf(src); got.SourceAt != want {
		t.Errorf("it names the revision %q, and the source digests to %q",
			got.SourceAt, want)
	}
	if got.SourceAt == "" {
		t.Error("it names no revision at all, so a proposal could outlive the names")
	}
	// AND A ROUTINE THAT TAKES NOTHING SAYS SO, rather than reporting an argument
	// somebody could be asked to fill in.
	plain := aLibraryHere(t)
	for _, c := range theLibrary(plain) {
		if len(c.Takes) != 0 {
			t.Errorf("%s reports taking %+v", c.ID, c.Takes)
		}
		if c.SourceAt == "" {
			t.Errorf("%s names no revision", c.ID)
		}
	}
}

// AND A TARGET THIS LIBRARY HAS NOTHING FOR IS SAID, NOT SILENTLY HONOURED.
//
// A stated target is authoritative about intent and is still a claim about this library.
// Honouring one for an application nothing is saved for produces an answer with no in-place
// routine in it and nothing saying why — which reads as "Marco has nothing for this" when the
// truth is "not in the library I am reading".
func TestATargetThisLibraryHasNothingForIsSaid(t *testing.T) {
	reg := aLibraryHere(t)
	r := &Runtime{}

	known := r.ResolveRoute(service.ResolveRoutePayload{
		Request: "ark sound", Target: "arkascended"})
	if strings.Contains(known.Answer.Context.Says, "nothing in this library") {
		t.Errorf("an application with routines was reported as having none: %q",
			known.Answer.Context.Says)
	}
	if known.Answer.ID != "arkascended/context/ark-sound" {
		t.Fatalf("an exact name did not resolve: %+v", known.Answer)
	}

	unknown := r.ResolveRoute(service.ResolveRoutePayload{
		Request: "ark sound", Target: "a-game-nobody-has"})
	if !strings.Contains(unknown.Answer.Context.Says, "nothing in this library is saved for") {
		t.Errorf("a target with nothing saved for it is not said: %q",
			unknown.Answer.Context.Says)
	}
	// AND IT IS STILL READ AGAINST WHAT THEY NAMED, because what they said is what they
	// meant: the global routine is offered and the in-place one for Ark is not.
	if unknown.Answer.Context.Basis != resolveroute.Stated {
		t.Errorf("a stated target was downgraded to %q", unknown.Answer.Context.Basis)
	}
	if unknown.Answer.Offered != 2 {
		t.Errorf("%d routine(s) were offered, want the global one and the one that "+
			"brings its own application forward", unknown.Answer.Offered)
	}
	_ = reg
}

// AND A LIBRARY THAT IS NOT THE CALLER'S IS NAMED, AND SELECTS NOTHING.
//
// Both sides answer this through `marcopaths`, so they agree unless the two processes were given
// different `$MARCO_ROUTES`. A surface selecting a routine out of a library Director was not
// reading would be offering a routine of that NAME rather than that routine.
func TestALibraryMismatchIsNamedAndSelectsNothing(t *testing.T) {
	reg := aLibraryHere(t)
	r := &Runtime{}

	// THE SAME REQUEST THAT RESOLVES CLEANLY WHEN THE LIBRARIES AGREE, so the refusal is
	// the mismatch and nothing else.
	agreed := r.ResolveRoute(service.ResolveRoutePayload{
		Request: "ark sound", Target: "arkascended", Library: reg.Dir})
	if agreed.Mismatch != "" || agreed.Answer.ID == "" {
		t.Fatalf("with the libraries agreeing the answer is %+v", agreed)
	}

	elsewhere := filepath.Join(t.TempDir(), "somebody-elses-routes")
	got := r.ResolveRoute(service.ResolveRoutePayload{
		Request: "ark sound", Target: "arkascended", Library: elsewhere})
	if got.Mismatch == "" {
		t.Fatal("a caller asking about a different library was served from this one")
	}
	// IT NAMES BOTH, so whoever reads it can see which two.
	for _, says := range []string{reg.Dir, elsewhere} {
		if !strings.Contains(got.Mismatch, says) {
			t.Errorf("the mismatch does not name %q: %s", says, got.Mismatch)
		}
	}
	// AND NOTHING IS SELECTED. Cleared HERE rather than left to a surface to remember:
	// an answer that must not be acted on does not carry the thing to act on.
	if got.Answer.ID != "" || got.Answer.App != "" || got.Answer.Slug != "" {
		t.Errorf("a mismatched answer still carries a routine to run: %+v", got.Answer)
	}
	if got.Answer.Kind == "run" {
		t.Errorf("a mismatched answer is still a run: %+v", got.Answer)
	}
	if got.Answer.Reply != got.Mismatch {
		t.Errorf("the answer a person reads does not say why: %q", got.Answer.Reply)
	}
	// AND THE LIBRARY IN THE ANSWER IS THE ONE IT ACTUALLY READ.
	if got.Answer.Library != reg.Dir {
		t.Errorf("the answer names library %q, want %q", got.Answer.Library, reg.Dir)
	}
}

// AND RESOLVING PERFORMS NOTHING.
//
// Zero ROUTE EXECUTION and zero input — not zero subprocesses, because the configured resolver
// plugin is one and that is the mechanism this reuses. What must not happen is a performer, a
// raise, a press, or a line of product data written.
func TestResolvingPerformsNothing(t *testing.T) {
	reg := aLibraryHere(t)
	before := everythingUnder(t, reg.Dir)
	runs := filepath.Join(marcopaths.Home(), marcopaths.RunsDir)
	runsBefore := everythingUnder(t, runs)

	r := &Runtime{}
	for _, request := range []string{"ark sound", "ark graphics", "make it nicer",
		"", "something nobody has"} {
		out := r.ResolveRoute(service.ResolveRoutePayload{
			Request: request, Target: "arkascended"})
		// AND NO RUN WAS CITED, which is what a performance leaves behind.
		if out.Answer.Kind == "run" && out.Answer.ID == "" {
			t.Errorf("%q answered run with nothing to run", request)
		}
	}

	// THE LIBRARY IS BYTE-FOR-BYTE WHAT IT WAS. Not "the routine I was looking at is
	// unchanged" — the whole of it, because a resolution that wrote anywhere has written.
	if now := everythingUnder(t, reg.Dir); !sameFiles(before, now) {
		t.Errorf("resolving changed the library:\nwas %v\nnow %v", before, now)
	}
	// AND NO RUN RECORD WAS RESERVED, which is the first thing a performance does.
	if now := everythingUnder(t, runs); !sameFiles(runsBefore, now) {
		t.Errorf("resolving left a run record:\nwas %v\nnow %v", runsBefore, now)
	}
	// AND THE REQUEST TYPE ITSELF STILL SAYS IT CHANGES NOTHING, which is what the
	// service's own gate on a read-only request reads.
	if service.RequestResolveRoute.Mutating() {
		t.Error("RESOLVE_ROUTE reports itself as mutating, so the service will treat " +
			"a question as a command")
	}
}

// everythingUnder is every file under a directory with its contents, or an empty map.
func everythingUnder(t *testing.T, dir string) map[string]string {
	t.Helper()
	out := map[string]string{}
	entries, err := os.ReadDir(dir)
	if err != nil {
		return out
	}
	for _, e := range entries {
		at := filepath.Join(dir, e.Name())
		if e.IsDir() {
			for k, v := range everythingUnder(t, at) {
				out[k] = v
			}
			continue
		}
		raw, rerr := os.ReadFile(at)
		if rerr != nil {
			t.Fatalf("reading %s: %v", at, rerr)
		}
		out[at] = string(raw)
	}
	return out
}

// sameFiles reports whether two readings of a tree are identical.
func sameFiles(was, now map[string]string) bool {
	if len(was) != len(now) {
		return false
	}
	for k, v := range was {
		if now[k] != v {
			return false
		}
	}
	return true
}

// AND WHAT EACH ROUTINE ANSWERS TO TRAVELS WITH IT.
//
// The wiring between the phrase file and the resolver, which neither side can hold alone:
// `internal/routes` stores the phrases and `internal/resolveroute` turns them into labels, and
// between them is this function. Without it every phrase in the library is invisible to Director
// while resolving perfectly at the door — one half of the product answering to a phrase and the
// other half not.
//
// A file left behind by a half-finished move offers nothing, because the read is the registry's
// own and an unoffered state yields no phrases.
func TestTheLibraryOffersWhatEachRoutineAnswersTo(t *testing.T) {
	reg := aLibraryHere(t)
	mine := routes.Route{App: "arkascended", Focus: true, Slug: "ark-graphics"}
	if err := reg.SaveAliases(mine, []string{"make it pretty"}); err != nil {
		t.Fatal(err)
	}
	// AND ONE LEFT BEHIND BY A MOVE THAT DID NOT FINISH.
	stale := routes.Route{Slug: "quit-everything"}
	if err := os.WriteFile(reg.AliasesPath(stale), []byte(
		`{"version":1,"route":"ark/focus/elsewhere","phrases":["shut it down"]}`),
		0o644); err != nil {
		t.Fatal(err)
	}
	byID := map[string]resolveroute.Candidate{}
	for _, c := range theLibrary(reg) {
		byID[c.ID] = c
	}
	got := byID["arkascended/focus/ark-graphics"]
	if len(got.Answers) != 1 || got.Answers[0] != "make it pretty" {
		t.Errorf("the routine is offered answering to %q", got.Answers)
	}
	if left := byID["global/quit-everything"]; len(left.Answers) != 0 {
		t.Errorf("phrases belonging to another identity were offered: %q",
			left.Answers)
	}
}
