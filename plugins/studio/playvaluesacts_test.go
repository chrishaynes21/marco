// AND NOTHING IS OFFERED WHILE A DEMONSTRATION IS BEING RECORDED.
func TestThePlayFieldsHoldOffWhileRecording(t *testing.T) {
	a, r := aRoutineThatNeedsText(t)
	a.recording = aHeldRecorder()
	if why := a.StartRecording("something else", ""); why != "" {
		t.Fatal(why)
	}
	defer a.CancelRecording()
	if got := a.PlayNeeds(r.ID); got.Why == "" {
		t.Errorf("the fields were offered during a recording: %+v", got)
	}
	if got := a.ReviewPlay(r.ID, map[string]string{"message": "x"}, nil, ""); got.Token != "" {
		t.Error("a run was prepared during a recording")
	}
}

// routesSource reads a routine's source, which these tests change to stage a stale confirmation.
func routesSource(reg routes.Registry, rt routes.Route) (string, error) {
	b, err := os.ReadFile(reg.Path(rt))
	return string(b), err
}

// containsArg is whether an argv carries exactly this term.
func containsArg(args []string, want string) bool {
	for _, a := range args {
		if a == want {
			return true
		}
	}
	return false
}

// aHeldRecorder is a recorder that starts and holds, so a recording is in progress.
func aHeldRecorder() func() recorder.Recorder {
	return func() recorder.Recorder { return &heldRecorder{} }
}

// AND THROUGH THE WINDOW, A MISSPELT NAME REFUSES RATHER THAN BEING DROPPED.
//
// The same gap at the surface somebody would meet it on, because `ReviewPlay` is what the page
// calls: a value typed into a box whose name does not match is somebody expecting text to appear
// and it never doing so, with a confirmation that looked right.
func TestAMisspeltValueIsRefusedByTheWindow(t *testing.T) {
	a, r := aRoutineThatNeedsText(t)
	got := a.ReviewPlay(r.ID, map[string]string{
		"message": "the text I meant", "mesage": "the one I mistyped"}, nil, "")
	if got.Token != "" {
		t.Fatal("a misspelt argument was dropped and the run was offered anyway")
	}
	if !strings.Contains(got.Why, "mesage") {
		t.Errorf("the refusal does not name it: %q", got.Why)
	}
	for _, v := range []string{"the text I meant", "the one I mistyped"} {
		if strings.Contains(got.Why, v) {
			t.Errorf("the refusal repeated a value: %q", got.Why)
		}
	}
}

// AND THE WINDOW HANDS THE CONFIRMED VERSION TO THE CHILD.
//
// This window's digest check happens before the spawn and the child reads the file after it, so
// the check alone leaves a gap a save can land in. The version travels on the argv, and it is the
// one the invocation was sealed with rather than a fresh reading — which is what makes it the
// version somebody actually confirmed.
func TestTheWindowHandsTheConfirmedVersionToTheChild(t *testing.T) {
	a, r := aRoutineThatNeedsText(t)
	got := a.ReviewPlay(r.ID, map[string]string{"message": "hello"}, nil, "")
	if got.Token == "" {
		t.Fatalf("the review was refused: %s", got.Why)
	}
	a.mu.Lock()
	held := a.invocations[got.Token]
	a.mu.Unlock()
	if held.SourceAt == "" {
		t.Fatal("the prepared invocation carries no version")
	}
	_, args, _ := a.doCommand(r, orchestrator.Pickable{},
		map[string]string{"message": "hello"}, held.SourceAt)
	if !containsArg(args, "--expect="+held.SourceAt) {
		t.Errorf("the command does not pin the confirmed version: %q", args)
	}
	// AND THE PLAIN PLAY PATH PINS NOTHING, because nothing was confirmed to it.
	_, plain, _ := a.doCommand(r, orchestrator.Pickable{}, nil, "")
	for _, arg := range plain {
		if strings.HasPrefix(arg, "--expect=") {
			t.Errorf("a run that confirmed nothing pinned a version: %q", plain)
		}
	}
}

// A CONFIRMED RUN IS PINNED TO THE VERSION IT WAS SEALED WITH.
//
// WRITTEN FOR A SURVIVOR, and the survivor was the one line nothing could reach: `ConfirmPlay`
// decides what the run is pinned to, and everything after that raises a window and starts a child
// — `marco do` performing real input, which this suite may never do. So the hand-off is a seam
// and this asserts the decision without the desktop.
//
// A fresh reading taken at this point would be a reading of whatever is on disk NOW, which is the
// very thing the pin exists to catch.
func TestAConfirmedRunIsPinnedToTheVersionItWasSealedWith(t *testing.T) {
	a, r := aRoutineThatNeedsText(t)
	got := a.ReviewPlay(r.ID, map[string]string{"message": "hello there"}, nil, "")
	if got.Token == "" {
		t.Fatalf("the review was refused: %s", got.Why)
	}
	a.mu.Lock()
	sealed := a.invocations[got.Token].SourceAt
	a.mu.Unlock()
	if sealed == "" {
		t.Fatal("the invocation carries no version")
	}
	var sawValues map[string]string
	var sawExpect, sawWindow string
	a.playing = func(_ Routine, window string, values map[string]string,
		expect string) string {
		sawWindow, sawValues, sawExpect = window, values, expect
		return ""
	}
	if said := a.ConfirmPlay(got.Token, "4660:77"); said != "" {
		t.Fatalf("confirming was refused: %s", said)
	}
	if sawExpect != sealed {
		t.Errorf("the run was pinned to %q, and the invocation was sealed with %q",
			sawExpect, sealed)
	}
	if sawWindow != "4660:77" {
		t.Errorf("the window came through as %q", sawWindow)
	}
	// AND THE VALUES ARE THE BACKEND'S COPY of what the confirmation showed.
	if sawValues["message"] != "hello there" {
		t.Errorf("the run was given %q", sawValues)
	}
}
