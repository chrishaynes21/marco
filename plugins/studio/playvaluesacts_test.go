// A TOKEN NOBODY MINTED CONFIRMS NOTHING, and a spent one cannot be pressed twice.
func TestOnlyATokenThisWindowPreparedCanBeConfirmed(t *testing.T) {
	a, r := aRoutineThatNeedsText(t)
	if why := a.ConfirmPlay("tok-nobody-minted", ""); why == "" {
		t.Error("a token this window never prepared was accepted")
	}
	got := a.ReviewPlay(r.ID, map[string]string{"message": "hello"}, nil, "")
	if got.Token == "" {
		t.Fatalf("the review was refused: %s", got.Why)
	}
	// CANCELLING LETS GO OF IT, which is what keeps the text from outliving the mind
	// somebody changed.
	a.CancelPlay(got.Token)
	if why := a.ConfirmPlay(got.Token, ""); why == "" {
		t.Error("a cancelled invocation was still confirmable")
	}
}

// AND A ROUTINE SAVED SINCE THE CONFIRMATION REFUSES, through the window.
func TestARoutineSavedSinceTheConfirmationIsRefusedInStudio(t *testing.T) {
	a, r := aRoutineThatNeedsText(t)
	got := a.ReviewPlay(r.ID, map[string]string{"message": "hello"}, nil, "")
	if got.Token == "" {
		t.Fatalf("the review was refused: %s", got.Why)
	}
	// SOMETHING SAVES IT AGAIN between reading the confirmation and pressing it.
	reg := a.reg()
	rt := r.route()
	src, err := routesSource(reg, rt)
	if err != nil {
		t.Fatal(err)
	}
	if err := reg.Replace(rt, src+"\n// and a change\n"); err != nil {
		t.Fatal(err)
	}
	why := a.ConfirmPlay(got.Token, "")
	if why == "" {
		t.Fatal("a routine saved again since the confirmation ran anyway")
	}
	if !strings.Contains(why, "saved again") {
		t.Errorf("the refusal does not say what happened: %q", why)
	}
}

// THE VALUES TRAVEL ON THE ONE COMMAND THE PRESS ALREADY SPAWNS.
//
// As flags, because an explicit identity deliberately never has its words read for arguments:
// appending `name:value` to this argv would do nothing at all. Sorted, so the same values produce
// the same command rather than whichever order a map hands them back in.
func TestTheValuesTravelAsFlagsOnTheRunsOwnCommand(t *testing.T) {
	a, r := aRoutineThatNeedsText(t)
	_, args, _ := a.doCommand(r, orchestrator.Pickable{}, map[string]string{
		"zeta": "last", "alpha": "first"}, "")
	var flags []string
	for _, arg := range args {
		if strings.HasPrefix(arg, "--arg=") {
			flags = append(flags, arg)
		}
	}
	if strings.Join(flags, " ") != "--arg=alpha=first --arg=zeta=last" {
		t.Errorf("the command carries %q", flags)
	}
	// AND THE IDENTITY IS STILL EXPLICIT, which is what makes the flags necessary.
	if !containsArg(args, "--play=write-a-note") {
		t.Errorf("the command does not name the route: %q", args)
	}
	// AND NOTHING WAS PUT INTO THE PHRASE. A value that fell into the words would make
	// the invocation a request about the world, carrying the text with it.
	for _, arg := range args {
		if arg == "first" || arg == "last" {
			t.Errorf("a value is a bare word on the command line: %q", args)
		}
	}
}

