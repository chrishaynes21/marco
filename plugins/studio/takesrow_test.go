package main

// A ROUTINE'S ROW SAYS WHAT IT ASKS FOR, the way it is typed: `cloud pull ‹resource›`.
// See [[ADR-317-the-widgets-help-opens-studio]].

import (
	"strings"
	"testing"

	"github.com/chaynes-simpleclouds/marco/internal/routes"
)

func takesFor(t *testing.T, body string) string {
	t.Helper()
	dir := t.TempDir()
	t.Setenv("MARCO_ROUTES", dir)
	t.Setenv("MARCO_CV", "off")
	a := newActs(t.TempDir())
	src := "// Auto-generated by `marco learn \"cloud pull\"`.\n" +
		"// Generation: 1.\nuse os.\n\nthe App is a script.\n\n" + body
	rt := routes.Route{App: "arkascended", Focus: true, Slug: "cloud-pull"}
	if err := (routes.Registry{Dir: dir}).Save(rt, src); err != nil {
		t.Fatal(err)
	}
	rs := a.Routines()
	if len(rs) != 1 {
		t.Fatalf("the library holds %d plays", len(rs))
	}
	if rs[0].Name != "cloud pull" {
		t.Fatalf("the name is %q", rs[0].Name)
	}
	return rs[0].Takes
}

const typed = "do OS's Type with \"{{%s}}\"...\n    when ok?\n        log \"done\".\n" +
	"    or?\n        log that's error.\n"

func TestARoutineRowSaysWhatItAsksFor(t *testing.T) {
	one := strings.ReplaceAll(typed, "%s", "resource")
	if got := takesFor(t, one); got != "‹resource›" {
		t.Errorf("one value reads %q, want ‹resource›, as the widget writes it", got)
	}
	two := one + strings.ReplaceAll(typed, "%s", "amount")
	if got := takesFor(t, two); got != "resource:‹resource› amount:‹amount›" {
		t.Errorf("two values read %q, want each named, as the widget writes them", got)
	}
	if got := takesFor(t, "log \"nothing asked\".\n"); got != "" {
		t.Errorf("a play that asks for nothing reads %q", got)
	}
	secret := one + "do OS's Secret with \"cloud-pull:password\"...\n" +
		"    when ok?\n        log \"done\".\n    or?\n        log that's error.\n"
	if got := takesFor(t, secret); got != "‹resource›" {
		t.Errorf("a secret is on the row (%q); the credential store answers it", got)
	}
}

func TestARoutineRowDrawsWhatItAsksForAfterItsName(t *testing.T) {
	browser := aBrowser()
	if browser == "" {
		t.Skip("no headless Chromium on this machine to render the page in")
	}
	be := strings.Replace(theRowBackend, "name: 'cloud pull stone',",
		"name: 'cloud pull', takes: '‹item›',", 1)
	title := renderForCounters(t, browser, be+`
let r = {}
setTimeout(() => {
  const h = (k) => document.getElementById('routine-' + k).querySelector('h3')
  r.named = h(K1).textContent === 'cloud pull ‹item›' ? 1 : 0
  const s = document.getElementById('routineTakes-' + K1)
  r.muted = s && getComputedStyle(s).fontWeight === '400' ? 1 : 0
  r.bare = document.getElementById('routineTakes-' + K2) ? 0 : 1
  document.title = 'err=0 ' + Object.keys(r).map(k => k + '=' + r[k]).join(' ')
}, 1100)`)
	n := counters(t, title, "named=")
	if n("named") != 1 {
		t.Errorf("the row does not read `cloud pull ‹item›`: %s", title)
	}
	if n("muted") != 1 {
		t.Errorf("what it asks for is not set apart from the name: %s", title)
	}
	if n("bare") != 1 {
		t.Errorf("a play that asks for nothing has a placeholder: %s", title)
	}
}
