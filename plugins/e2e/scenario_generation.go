//go:build windows

package main

// SCENARIO: A ROUTINE'S OWN RECORDING, REBUILT AND REVIEWED IN THE REAL STUDIO, REPLACED ONLY
// WHEN SOMEBODY PRESSES REPLACE.
//
// # What is being established, and what the oracle is
//
// The flow is four steps and three of them must change nothing on disk. So the account this
// scenario trusts is THE FILE, read by this harness off the library Studio was given — not what
// the window says about it. Studio's own words are read too and reported as evidence, because a
// window that says `unstated` about a routine and then replaces a different one is a defect this
// product has had; but the verdict is the bytes.
//
//	Review  the panel comes up, with both sources in it, and the file is untouched
//	Cancel  the panel goes, and the file is STILL untouched
//	Review  again
//	Replace the file now holds what the generator writes, and nothing else moved
//
// # Why the harness takes the generation line out of the saved routine first
//
// Because every routine this build can seed is written by this build, so every one of them reads
// as the current generation and is offered nothing to compare against. The case the flow exists
// for is a routine saved WITHOUT the line, and the only honest way to have one on a current build
// is to remove it.
//
// What that arrangement establishes is therefore bounded, and the boundary is worth stating: it
// exercises the flow against a routine that states no generation. It is NOT a claim that any
// particular older routine in anybody's library looks like this, and nothing here reconstructs a
// generation for an unstamped file — the reading is `unstated`, which is all the file supports.
//
// # No input is sent, and none of this is a performance
//
// Nothing here presses Play. The fixture is open because the routine has to be a real one, with
// real window measurements from a real window, generated by the production path — a review of a
// hand-written routine would be a review of something the product does not make. Its window is
// never pressed.
//
// Physical recording capture is NOT EXERCISED here, as everywhere: the demonstration behind the
// routine is seeded, which this harness says in its own report.
//
// See [[ADR-262-a-routine-states-which-generation-wrote-it]].

import (
	"fmt"
	"strings"
	"time"

	"github.com/chaynes-simpleclouds/marco/internal/orchestrator"
	"github.com/chaynes-simpleclouds/marco/internal/routes"
)

// aReviewedRebuildReplacesTheRoutine is the whole flow, in one run, because it is one claim.
func aReviewedRebuildReplacesTheRoutine(w *world) result {
	started := time.Now()
	st, err := setUpSeeded(w, func(f *fixtureRun) (seededRoutine, error) {
		s, err := seedPresses(f, w.art, "fixture review", 0, "Save")
		if err != nil {
			return s, err
		}
		return s, statingNoGeneration(&s, w.art)
	})
	if err != nil {
		return ending(started, err)
	}
	defer st.down()

	saved, err := readFileString(st.seed.path)
	if err != nil {
		return ending(started, err)
	}
	// THE ARRANGEMENT HELD. A routine that still states a generation would be offered
	// nothing to review, and every assertion below would be about a disabled button.
	if g := orchestrator.GenerationOf(saved); g.Reading != orchestrator.GenerationUnstated {
		return skip(started, fmt.Sprintf("the seeded routine reads as %q rather than "+
			"stating no generation, so there is nothing for this to review",
			g.Reading))
	}
	// AND STUDIO SAYS SO, in its own words, before anything is pressed. Evidence rather
	// than the verdict — but a window that offered a review while saying the routine was
	// current would be offering a comparison nobody asked for.
	shot, err := st.s.look()
	if err != nil {
		return ending(started, err)
	}
	if !shot.says("does not state which generation") {
		st.fail()
		return fail(started, "Studio does not say that the chosen routine states no "+
			"generation, so what it is offering to review is not what this "+
			"scenario arranged",
			fmt.Sprintf("what the window says: %s", strings.Join(shot.ids(), " ")))
	}
	w.art.step("Studio says the routine states no generation, and offers a review")

	// ── REVIEW: THE PANEL COMES UP AND THE FILE IS UNTOUCHED ──
	if _, err := st.s.waitFor(10*time.Second, "routineReviewBtn", enabled); err != nil {
		st.fail()
		return fail(started, fmt.Sprintf("Studio will not offer to review a rebuilt "+
			"version of %q: %v", st.seed.name, err))
	}
	if err := st.s.press("routineReviewBtn"); err != nil {
		return ending(started, err)
	}
	if err := st.s.waitForReview(); err != nil {
		st.fail()
		return fail(started, err.Error())
	}
	if why := theFileMoved(st.seed.path, saved, "while the review was on screen"); why != "" {
		st.fail()
		return fail(started, why)
	}
	w.art.step("the review is up and the saved routine is untouched")

	// ── CANCEL: THE PANEL GOES AND THE FILE IS STILL UNTOUCHED ──
	if err := st.s.press("routineReviewCancelBtn"); err != nil {
		return ending(started, err)
	}
	if err := st.s.waitForNoReview(); err != nil {
		st.fail()
		return fail(started, err.Error())
	}
	if why := theFileMoved(st.seed.path, saved, "when the review was cancelled"); why != "" {
		st.fail()
		return fail(started, why)
	}
	w.art.step("the review was cancelled and the saved routine is untouched")

	// ── REVIEW AGAIN, AND REPLACE ──
	if err := st.s.press("routineReviewBtn"); err != nil {
		return ending(started, err)
	}
	if err := st.s.waitForReview(); err != nil {
		st.fail()
		return fail(started, err.Error())
	}
	if _, err := st.s.waitFor(10*time.Second, "routineReplaceBtn", enabled); err != nil {
		st.fail()
		return fail(started, fmt.Sprintf("Studio will not offer to replace %q with "+
			"the version it rebuilt: %v", st.seed.name, err))
	}
	if err := st.s.press("routineReplaceBtn"); err != nil {
		return ending(started, err)
	}
	now, err := theReplacedRoutine(st.seed.path, saved)
	if err != nil {
		st.fail()
		return fail(started, err.Error())
	}
	w.art.keep("reviewed-"+st.seed.route.Slug+".marco", []byte(now))

	why := firstOf(
		theReplacementIsNotWhatTheGeneratorWrites(now, saved),
		theRoutineDidNotKeepItsPlace(st, now),
	)
	if why != "" {
		st.fail()
		return fail(started, why,
			fmt.Sprintf("the file now holds:\n%s", now))
	}
	return pass(started,
		fmt.Sprintf("the review was up twice and cancelled once, and the file on disk "+
			"did not change until Replace was pressed"),
		fmt.Sprintf("it now states generation %d, where before it stated none",
			orchestrator.GenerationNow()),
		fmt.Sprintf("and it is still %s, with its demonstration beside it",
			routeIdentity(st.seed)))
}

// ── THE ARRANGEMENT ────────────────────────────────────────────────────────────

// statingNoGeneration takes the generation line out of a routine this build just wrote.
//
// See the note at the top of this file for why, and for what it does and does not establish. It
// is written down in the artifacts as an arrangement rather than slipped in, because a report
// that showed a routine stating nothing without saying the harness made it so would be reporting
// a library this build cannot produce.
func statingNoGeneration(s *seededRoutine, art *artifacts) error {
	raw, err := readFileString(s.path)
	if err != nil {
		return err
	}
	var kept []string
	var took int
	for _, line := range strings.Split(raw, "\n") {
		if strings.HasPrefix(strings.TrimSpace(line), "// Generation: ") {
			took++
			continue
		}
		kept = append(kept, line)
	}
	if took == 0 {
		return fmt.Errorf("the seeded routine states no generation already, so this "+
			"build is not writing one and there is nothing to arrange: %s", s.path)
	}
	src := strings.Join(kept, "\n")
	if err := writeFileString(s.path, src); err != nil {
		return err
	}
	s.source = src
	art.step("ARRANGED: took the generation line out of %s, so it states none — see "+
		"scenario_generation.go for what that does and does not establish", s.path)
	art.keep("stating-no-generation-"+s.route.Slug+".marco", []byte(src))
	return nil
}

// waitForReview waits until the review is on screen with both versions in it.
//
// By what is IN it and not by the panel's presence. A panel that came up empty, or with one pane,
// would satisfy "the review is showing" and be no comparison at all. Two things are looked for:
// the line the panel leads with, which is the promise that nothing has been written; and the
// generation line, which exists in the rebuilt version and in nothing else on this page — so
// seeing it is seeing that the rebuilt source is rendered rather than an empty pane with a label
// over it.
func (s *studioRun) waitForReview() error {
	ok, saw := until(20*time.Second, func() (bool, string) {
		shot, err := s.look()
		if err != nil {
			return false, err.Error()
		}
		if _, there := shot.byID("routineReplaceBtn"); !there {
			return false, "the review is not on screen"
		}
		switch {
		case !shot.says("Nothing has been written yet"):
			return false, "the review does not say that nothing has been written"
		case !shot.says(fmt.Sprintf("Generation: %d",
			orchestrator.GenerationNow())):
			return false, "the rebuilt version is not rendered in it"
		}
		return true, "showing"
	})
	if !ok {
		return fmt.Errorf("Studio did not show a review of the rebuilt version: %s", saw)
	}
	return nil
}

// waitForNoReview waits until the review is off the screen.
func (s *studioRun) waitForNoReview() error {
	ok, saw := until(20*time.Second, func() (bool, string) {
		shot, err := s.look()
		if err != nil {
			return false, err.Error()
		}
		if _, there := shot.byID("routineReplaceBtn"); there {
			return false, "the review is still on screen"
		}
		return true, "gone"
	})
	if !ok {
		return fmt.Errorf("the review did not go away when it was cancelled: %s", saw)
	}
	return nil
}

// ── THE DISAGREEMENTS ──────────────────────────────────────────────────────────

// theFileMoved is the claim that nothing was written, read off the file itself.
func theFileMoved(path, was, when string) string {
	now, err := readFileString(path)
	if err != nil {
		return fmt.Sprintf("the saved routine could not be read %s: %v", when, err)
	}
	if now == was {
		return ""
	}
	return fmt.Sprintf("the saved routine changed %s, and nothing had been replaced "+
		"yet:\n--- was ---\n%s\n--- now ---\n%s", when, was, now)
}

// theReplacedRoutine waits for the replacement to land and returns what the file holds.
//
// Waited for rather than read at once: pressing the button returns when the control was invoked,
// and the call behind it happens after that. A read taken immediately would be racing the write
// and would report a replacement that did not happen.
func theReplacedRoutine(path, was string) (string, error) {
	var now string
	ok, saw := until(30*time.Second, func() (bool, string) {
		got, err := readFileString(path)
		if err != nil {
			return false, err.Error()
		}
		if got == was {
			return false, "the file still holds what it did before"
		}
		now = got
		return true, "replaced"
	})
	if !ok {
		return was, fmt.Errorf("Replace was pressed and the saved routine never "+
			"changed: %s", saw)
	}
	return now, nil
}

// theReplacementIsNotWhatTheGeneratorWrites checks the one difference this run arranged.
//
// The harness took the generation line out; a rebuild under today's rules puts it back and
// changes nothing else, because the same generator wrote both. So the replaced file has to be the
// saved one with that line restored — which is a far stronger claim than "it changed", and it is
// the claim the flow makes: what was reviewed is what was written.
func theReplacementIsNotWhatTheGeneratorWrites(now, was string) string {
	g := orchestrator.GenerationOf(now)
	if g.Reading != orchestrator.GenerationCurrent {
		return fmt.Sprintf("the replaced routine reads as %q rather than stating the "+
			"generation this build writes (%s)", g.Reading, g.Why)
	}
	var without []string
	for _, line := range strings.Split(now, "\n") {
		if strings.HasPrefix(strings.TrimSpace(line), "// Generation: ") {
			continue
		}
		without = append(without, line)
	}
	if rest := strings.Join(without, "\n"); rest != was {
		return fmt.Sprintf("the replacement changed more than the generation line, "+
			"and the same generator wrote both — so what was written is not a "+
			"rebuild of the same demonstration:\n--- was ---\n%s\n--- now, "+
			"without its generation line ---\n%s", was, rest)
	}
	return ""
}

// theRoutineDidNotKeepItsPlace checks that a replacement replaced rather than moved.
//
// A routine that came back from a review under another scope is a routine that stopped working
// the way it did — `<app>/focus` to `<app>/context` is one that no longer runs from anywhere —
// and the person reviewed a source, not a move. Its demonstration has to still be there too, or
// it can never be reviewed again.
func theRoutineDidNotKeepItsPlace(st *stage, now string) string {
	reg := routes.Registry{Dir: routesDir()}
	if at := reg.Path(st.seed.route); at != st.seed.path {
		return fmt.Sprintf("the routine was at %s and is now at %s", st.seed.path, at)
	}
	if !reg.HasRecording(st.seed.route) {
		return "the replacement took the routine's demonstration with it, so it can " +
			"never be rebuilt again"
	}
	if c, _ := orchestrator.ContractOf(now); c != orchestrator.Guarded {
		return fmt.Sprintf("the routine was guarded and the replacement reads as %q, "+
			"so the rebuild changed what its presses promise", c)
	}
	return ""
}
