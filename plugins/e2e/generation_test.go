//go:build windows

package main

// THE REVIEW-AND-REPLACE SCENARIO, AND WHAT CAN BE CHECKED ABOUT IT WITHOUT A DESKTOP.
//
// It ran green on a desktop on 2026-10-27, first time, so what is held here is the name, the
// claims the verdict rests on, the call sites that ask them, and the one piece of arithmetic in
// it that does not need a window: the comparison that says a replacement is the saved routine
// with its generation line restored and nothing else changed.
//
// That comparison is the whole strength of the scenario. "The file changed" would pass on a
// window that wrote anything at all into it.

import (
	"go/ast"
	"go/parser"
	"go/token"
	"strings"
	"testing"

	"github.com/chaynes-simpleclouds/marco/internal/orchestrator"
)

// IT RUNS ORDINARILY, IT NEEDS A DESKTOP, AND NOBODY ELSE'S SELECTOR TAKES IT.
//
// The gate half of this test is gone and its going is the point: it ran green on a desktop on
// 2026-10-27, first time, so it is a regression check now and belongs in every default run. The
// NAME claim outlives the gate — a scenario swept up by `-only text` or `-only button` would be
// run by somebody who typed a flag for a different reason.
func TestTheReviewScenarioRunsLikeAnyOther(t *testing.T) {
	var found int
	for _, s := range scenarios() {
		if !strings.HasPrefix(s.name, "generation/") {
			continue
		}
		found++
		if s.onlyWhenAsked {
			t.Errorf("%q has run green on a desktop and is gated out of a default "+
				"run again, so the regression it was written to catch is only "+
				"checked when somebody remembers to name it", s.name)
		}
		if s.layer != layerDesktop {
			t.Errorf("%q is labelled %q and it needs a desktop", s.name, s.layer)
		}
		for _, family := range families(t) {
			if family == "generation" {
				continue
			}
			if strings.Contains(s.name, family) {
				t.Errorf("%q contains %q, so `-only %s` — another family's "+
					"gate — would select it", s.name, family, family)
			}
		}
		if s.about == "" || s.run == nil {
			t.Errorf("%q is not a runnable, described scenario", s.name)
		}
	}
	if found != 1 {
		t.Errorf("%d review scenario(s) are registered, want the one that was "+
			"written: the whole flow in one run", found)
	}
}

// A REPLACEMENT IS THE SAVED ROUTINE WITH ITS GENERATION LINE BACK, AND NOTHING ELSE CHANGED.
//
// The scenario's strongest claim, and the one that makes the run worth doing: the same generator
// wrote the seeded routine and the rebuilt one, so the only difference a correct replacement can
// have is the line the harness took out. Anything else written into that file — a rescope, a
// different simplification, a stale draft, an empty file — is a finding.
func TestAReplacementThatChangedAnythingElseIsAFinding(t *testing.T) {
	const was = "// Auto-generated by `marco learn \"fixture review\"`.\nuse os.\n\n" +
		"the FixtureReview is an actor.\n"
	// THE CORRECT ONE: the same source with the line restored where the generator puts
	// it, which is after the header and before `use os.`
	restored := strings.Replace(was, "use os.\n",
		"// Generation: 1.\nuse os.\n", 1)
	if why := theReplacementIsNotWhatTheGeneratorWrites(restored, was); why != "" {
		t.Errorf("a replacement that is the saved routine with its generation line "+
			"back is reported as a finding: %s", why)
	}
	for _, c := range []struct {
		what string
		now  string
		says string
	}{
		{"it states no generation at all", was, "rather than stating the generation"},
		{"it states a generation this build cannot explain",
			strings.Replace(was, "use os.\n", "// Generation: 97.\nuse os.\n", 1),
			"rather than stating the generation"},
		{"it is empty", "// Generation: 1.\n", "changed more than the generation line"},
		{"something else in it moved",
			strings.Replace(restored, "the FixtureReview is an actor",
				"the SomethingElse is an actor", 1),
			"changed more than the generation line"},
	} {
		t.Run(c.what, func(t *testing.T) {
			why := theReplacementIsNotWhatTheGeneratorWrites(c.now, was)
			if why == "" {
				t.Fatalf("a replacement where %s is reported as a correct "+
					"rebuild", c.what)
			}
			if !strings.Contains(why, c.says) {
				t.Errorf("the finding is %q and does not say %q", why, c.says)
			}
		})
	}
	// AND THE GENERATION IT LOOKS FOR IS THE ONE THIS BUILD WRITES, not the literal 1
	// above: the day there is a generation 2, the fixture in this test is what has to
	// change and the scenario must not quietly go on asserting the old number.
	if orchestrator.GenerationNow() != 1 {
		t.Skip("this build writes generation " +
			string(rune('0'+orchestrator.GenerationNow())) +
			"; the fixtures above are written for 1")
	}
}

// AND A FILE THAT MOVED WHILE NOTHING SHOULD HAVE BEEN WRITTEN IS A FINDING, WITH BOTH SOURCES.
//
// The claim three of the scenario's four steps rest on. The sentence carries both versions,
// because "the file changed" with nothing to compare leaves whoever reads the report unable to
// tell a replacement from a truncation.
func TestAFileThatChangedBeforeReplaceIsAFinding(t *testing.T) {
	dir := t.TempDir()
	at := dir + "/a.marco"
	if err := writeFileString(at, "use os.\n"); err != nil {
		t.Fatal(err)
	}
	if why := theFileMoved(at, "use os.\n", "while the review was up"); why != "" {
		t.Errorf("an untouched file is reported as changed: %s", why)
	}
	if err := writeFileString(at, "use os.\n// and something else\n"); err != nil {
		t.Fatal(err)
	}
	why := theFileMoved(at, "use os.\n", "while the review was up")
	if why == "" {
		t.Fatal("a file that was written to before Replace is reported as untouched, " +
			"so the scenario would pass on a window that replaces a routine " +
			"without being asked")
	}
	for _, want := range []string{"while the review was up", "--- was ---", "--- now ---"} {
		if !strings.Contains(why, want) {
			t.Errorf("the finding is %q and does not carry %q", why, want)
		}
	}
	// AND A FILE THAT IS GONE IS NOT SILENTLY AN UNCHANGED ONE.
	if theFileMoved(dir+"/nothing.marco", "use os.\n", "at the end") == "" {
		t.Error("a routine that has disappeared is reported as untouched")
	}
}

// AND THE SCENARIO ASKS EVERY QUESTION ITS VERDICT RESTS ON.
//
// It runs only on a desktop, where a scenario that stopped asking one of these would go on
// passing. BY AST AND NOT BY SEARCHING THE FILE, which is the lesson the text family's mutation
// gate taught: a text search from the function's own line finds each claim's DEFINITION further
// down the same file, so the assertion is satisfied by the functions existing rather than by
// anything calling them.
func TestTheReviewScenarioAsksEveryQuestionItsVerdictRestsOn(t *testing.T) {
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, "scenario_generation.go", nil, 0)
	if err != nil {
		t.Fatalf("parsing scenario_generation.go: %v", err)
	}
	var fn *ast.FuncDecl
	for _, decl := range file.Decls {
		if d, ok := decl.(*ast.FuncDecl); ok &&
			d.Name.Name == "aReviewedRebuildReplacesTheRoutine" {
			fn = d
		}
	}
	if fn == nil {
		t.Fatal("the scenario is gone; it is the desktop half of this contract")
	}
	asks := map[string]bool{}
	ast.Inspect(fn, func(n ast.Node) bool {
		switch c := n.(type) {
		case *ast.CallExpr:
			switch f := c.Fun.(type) {
			case *ast.Ident:
				asks[f.Name] = true
			case *ast.SelectorExpr:
				asks[f.Sel.Name] = true
			}
		}
		return true
	})
	for _, claim := range []string{
		// THE THREE STEPS THAT MUST WRITE NOTHING, and the one that must.
		"theFileMoved",
		"theReplacedRoutine",
		"theReplacementIsNotWhatTheGeneratorWrites",
		"theRoutineDidNotKeepItsPlace",
		// AND THE WINDOW REACHING THE STATES IT CLAIMS TO: a scenario that
		// pressed Cancel without waiting for the panel to go would read the file
		// before the press had been handled, and call that "nothing was written".
		"waitForReview",
		"waitForNoReview",
	} {
		if !asks[claim] {
			t.Errorf("the scenario never asks %s, so its verdict does not rest "+
				"on it", claim)
		}
	}
	// AND IT PRESSES ALL FOUR CONTROLS. The flow IS the four presses; three of them
	// with the fourth missing is a different scenario that would still pass.
	pressed := map[string]bool{}
	ast.Inspect(fn, func(n ast.Node) bool {
		call, ok := n.(*ast.CallExpr)
		if !ok || len(call.Args) != 1 {
			return true
		}
		sel, ok := call.Fun.(*ast.SelectorExpr)
		if !ok || sel.Sel.Name != "press" {
			return true
		}
		if lit, ok := call.Args[0].(*ast.BasicLit); ok {
			pressed[strings.Trim(lit.Value, `"`)] = true
		}
		return true
	})
	for _, id := range []string{"routineReviewBtn", "routineReviewCancelBtn",
		"routineReplaceBtn"} {
		if !pressed[id] {
			t.Errorf("the scenario never presses %s, so it does not exercise the "+
				"flow it is named for", id)
		}
	}
	// AND IT PRESSES REVIEW TWICE, which is what makes the cancel more than a
	// decoration: the second review is the one Replace acts on.
	var reviews int
	ast.Inspect(fn, func(n ast.Node) bool {
		call, ok := n.(*ast.CallExpr)
		if !ok {
			return true
		}
		sel, ok := call.Fun.(*ast.SelectorExpr)
		if !ok || sel.Sel.Name != "press" || len(call.Args) != 1 {
			return true
		}
		if lit, ok := call.Args[0].(*ast.BasicLit); ok &&
			strings.Trim(lit.Value, `"`) == "routineReviewBtn" {
			reviews++
		}
		return true
	})
	if reviews != 2 {
		t.Errorf("the scenario presses Review %d time(s); the flow is review, "+
			"cancel, review, replace", reviews)
	}
}
