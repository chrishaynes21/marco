package orchestrator

// WHAT A ROUTINE WILL TYPE, AND THE THREE THINGS THAT CAN CHANGE UNDER A CONFIRMATION.
//
// The invocation is prepared, handed to a surface, and handed back. Between those two moments the
// routine can be saved again, the values can be edited, and the invocation can be a different one
// altogether — so all three are asked again, and the token is recomputed from what the struct NOW
// holds rather than compared against a reading taken when it was made.
//
// See [[Text-arguments-proposal-2026-10-30]].

import (
	"os"
	"strings"
	"testing"

	"github.com/chaynes-simpleclouds/marco/internal/routes"
)

// aRoutineWithAValue is a saved routine that types one supplied value.
func aRoutineWithAValue(t *testing.T) (Deps, routes.Route) {
	t.Helper()
	d := Deps{Reg: routes.Registry{Dir: t.TempDir()}, Out: &strings.Builder{}}
	rt := routes.Route{App: "notepad", Slug: "write-a-note"}
	src := "// Auto-generated by `marco learn \"write a note with message\"`.\n" +
		"use os.\n\nthe App is a script.\n\n" +
		"do OS's Type with \"{{message}}\"...\n" +
		"    when ok?\n        log \"done\".\n    or?\n        log that's error.\n"
	if err := d.Reg.Save(rt, src); err != nil {
		t.Fatal(err)
	}
	return d, rt
}

// A PREPARED INVOCATION SAYS WHAT IT WOULD TYPE, AND NOTHING IS WRITTEN.
func TestAnInvocationSaysWhatItWouldType(t *testing.T) {
	d, rt := aRoutineWithAValue(t)
	was, _ := os.ReadFile(d.Reg.Path(rt))
	i, err := d.PrepareInvocation(rt, map[string]string{"message": "hello there"})
	if err != nil {
		t.Fatalf("PrepareInvocation: %v", err)
	}
	if !i.Runnable() || !i.Needs() {
		t.Fatalf("the invocation reads as %+v", i)
	}
	if len(i.Says) != 1 || !strings.Contains(i.Says[0], "hello there") ||
		!strings.Contains(i.Says[0], "message") {
		t.Errorf("the confirmation says %q", i.Says)
	}
	if now, _ := os.ReadFile(d.Reg.Path(rt)); string(now) != string(was) {
		t.Error("preparing an invocation wrote to the routine")
	}
}

// AND A MISSING VALUE IS A REASON RATHER THAN A TOKEN.
//
// The surface must not be able to confirm what the door would decline, and the sentence is the
// contract's own: a window with a copy of the rule is a window that offers a press and is then
// told off for it.
func TestAnInvocationWithoutItsValueCannotBeConfirmed(t *testing.T) {
	d, rt := aRoutineWithAValue(t)
	i, err := d.PrepareInvocation(rt, nil)
	if err != nil {
		t.Fatalf("PrepareInvocation: %v", err)
	}
	if i.Runnable() {
		t.Fatal("an invocation with no value for its text was offered as runnable")
	}
	if !strings.Contains(i.Why, "message") {
		t.Errorf("the reason does not name the argument: %q", i.Why)
	}
	if i.Token != "" {
		t.Error("it carries a token that could be confirmed")
	}
}

// AN EXPLICITLY EMPTY VALUE IS CONFIRMABLE, AND THE CONFIRMATION SAYS SO IN WORDS.
//
// A blank line in the confirmation is a blank nobody can tell from a mistake, so the one case
// where a routine is about to type nothing says that it is about to type nothing.
func TestAnExplicitlyEmptyValueIsConfirmableAndSaidInWords(t *testing.T) {
	d, rt := aRoutineWithAValue(t)
	i, err := d.PrepareInvocation(rt, map[string]string{"message": ""})
	if err != nil {
		t.Fatalf("PrepareInvocation: %v", err)
	}
	if !i.Runnable() {
		t.Fatalf("an empty value somebody gave on purpose is refused: %q", i.Why)
	}
	if len(i.Says) != 1 || !strings.Contains(i.Says[0], "nothing") {
		t.Errorf("the confirmation says %q", i.Says)
	}
	if why := d.ConfirmInvocation(i); why != "" {
		t.Errorf("confirming it was refused: %s", why)
	}
}

// AND A CONFIRMED INVOCATION STILL ASKS WHETHER THE ROUTINE MOVED.
func TestARoutineSavedSinceTheConfirmationRefuses(t *testing.T) {
	d, rt := aRoutineWithAValue(t)
	i, err := d.PrepareInvocation(rt, map[string]string{"message": "hello"})
	if err != nil {
		t.Fatalf("PrepareInvocation: %v", err)
	}
	if why := d.ConfirmInvocation(i); why != "" {
		t.Fatalf("the control was refused: %s", why)
	}
	// SOMETHING SAVES THE ROUTINE AGAIN.
	src, _ := os.ReadFile(d.Reg.Path(rt))
	if err := d.Reg.Replace(rt, string(src)+"\n// and a change\n"); err != nil {
		t.Fatal(err)
	}
	why := d.ConfirmInvocation(i)
	if why == "" {
		t.Fatal("a routine saved again since the confirmation ran anyway")
	}
	if !strings.Contains(why, "saved again") {
		t.Errorf("the refusal does not say what happened: %q", why)
	}
}

// AND A VALUE CHANGED AFTER THE CONFIRMATION REFUSES.
//
// THE CASE SEALING A MAP BY REFERENCE WOULD MISS. The invocation is handed to a surface and handed
// back; if the token were a digest taken at preparation and stored, the stored digest and the map
// would move together and the comparison would always succeed. `sealed` recomputes from what the
// struct now holds, so the two diverge exactly when somebody has changed what it says it showed.
func TestAValueChangedAfterTheConfirmationRefuses(t *testing.T) {
	d, rt := aRoutineWithAValue(t)
	i, err := d.PrepareInvocation(rt, map[string]string{"message": "as it was shown"})
	if err != nil {
		t.Fatalf("PrepareInvocation: %v", err)
	}
	// THE SURFACE EDITS WHAT IT IS HOLDING, between reading the confirmation and
	// confirming it.
	i.Values["message"] = "something else entirely"
	why := d.ConfirmInvocation(i)
	if why == "" {
		t.Fatal("a value changed after the confirmation was typed anyway")
	}
	if !strings.Contains(why, "no longer what the confirmation showed") {
		t.Errorf("the refusal does not say what happened: %q", why)
	}
	// AND THE REFUSAL DOES NOT REPEAT EITHER VALUE, because it is a diagnostic.
	for _, v := range []string{"as it was shown", "something else entirely"} {
		if strings.Contains(why, v) {
			t.Errorf("the refusal repeated a value: %q", why)
		}
	}
}

// AND A VALUE ADDED AFTER THE CONFIRMATION REFUSES TOO.
//
// The other direction of the same gap: not changing what was shown but adding what was not.
func TestAValueAddedAfterTheConfirmationRefuses(t *testing.T) {
	d, rt := aRoutineWithAValue(t)
	i, err := d.PrepareInvocation(rt, map[string]string{"message": "hello"})
	if err != nil {
		t.Fatalf("PrepareInvocation: %v", err)
	}
	i.Values["smuggled"] = "and another"
	if why := d.ConfirmInvocation(i); why == "" {
		t.Fatal("a value nobody confirmed was accepted")
	}
}

// AND AN INVOCATION NOBODY PREPARED CONFIRMS NOTHING.
func TestAnInvocationNobodyPreparedCannotBeConfirmed(t *testing.T) {
	d, rt := aRoutineWithAValue(t)
	if why := d.ConfirmInvocation(Invocation{Route: rt, ID: rt.ID()}); why == "" {
		t.Error("an invocation with no token was confirmed")
	}
}

// A ROUTINE THAT NEEDS NOTHING IS UNCHANGED BY ANY OF THIS.
//
// No confirmation is put to anybody about a routine whose every press was demonstrated, which is
// what keeps this slice from putting a question in front of every Play in the library.
func TestARoutineThatNeedsNothingIsUnchanged(t *testing.T) {
	d := Deps{Reg: routes.Registry{Dir: t.TempDir()}, Out: &strings.Builder{}}
	rt := routes.Route{App: "notepad", Slug: "press-b"}
	if err := d.Reg.Save(rt, "use os.\n\nthe App is a script.\n\n"+
		"do OS's Key with \"b\"...\n    when ok?\n        log \"done\".\n"+
		"    or?\n        log that's error.\n"); err != nil {
		t.Fatal(err)
	}
	i, err := d.PrepareInvocation(rt, nil)
	if err != nil {
		t.Fatalf("PrepareInvocation: %v", err)
	}
	if i.Needs() {
		t.Error("a routine with no arguments is reported as needing one")
	}
	if !i.Runnable() {
		t.Errorf("it cannot be run: %q", i.Why)
	}
	if len(i.Says) != 0 {
		t.Errorf("there is a confirmation to read for a routine that needs nothing: %q",
			i.Says)
	}
}

// AND A VALUE FOR SOMETHING THE ROUTINE DOES NOT TAKE IS NOT CARRIED.
//
// Left out rather than carried and refused later: carried, it would be in the token and in the
// confirmation as though it were going to be typed, which is the opposite of what a confirmation
// is for. The door still refuses it — that is `CheckArgs`' job — and what this must not do is
// SHOW it.
func TestAValueTheRoutineDoesNotTakeIsNotShownAsSomethingItWillType(t *testing.T) {
	d, rt := aRoutineWithAValue(t)
	i, err := d.PrepareInvocation(rt, map[string]string{
		"message": "hello", "subject": "not a thing this routine types"})
	if err != nil {
		t.Fatalf("PrepareInvocation: %v", err)
	}
	if _, ok := i.Values["subject"]; ok {
		t.Error("a value the routine does not take is carried as one it will type")
	}
	for _, said := range i.Says {
		if strings.Contains(said, "not a thing") {
			t.Errorf("the confirmation shows it: %q", said)
		}
	}
}

// AND TWO DIFFERENT SETS OF VALUES DO NOT SEAL ALIKE.
//
// The length-delimited join, as a claim. Joining a name and a value plainly would let `a=bc`
// digest the same as `ab=c` — a collision somebody could choose, in the one field whose whole job
// is to notice a change.
func TestTwoDifferentSetsOfValuesDoNotSealAlike(t *testing.T) {
	base := Invocation{ID: "notepad/context/x", SourceAt: "deadbeef"}
	// THE COLLISION A PLAIN JOIN ALLOWS, which the first draft of this test missed by
	// picking two sets that differ as strings anyway: `a`/`bc` and `ab`/`c` join to
	// `a=bc` and `ab=c`, which are not equal. The pair that DOES collide moves the
	// separator rather than the boundary — a value containing `=` against a name
	// containing one — and both reach here, because the values are a map a surface fills.
	one := base
	one.Values = map[string]string{"a": "b=c"}
	two := base
	two.Values = map[string]string{"a=b": "c"}
	if one.sealed().Token == two.sealed().Token {
		t.Error("two different sets of values seal to the same token, so a value " +
			"could be swapped for one that digests alike")
	}
	// AND THE SAME VALUES SEAL ALIKE WHATEVER ORDER A MAP HANDS THEM BACK IN.
	same := base
	same.Values = map[string]string{"a": "1", "b": "2"}
	other := base
	other.Values = map[string]string{"b": "2", "a": "1"}
	if same.sealed().Token != other.sealed().Token {
		t.Error("one set of values seals differently depending on map order")
	}
}

// A VALID VALUE BESIDE A MISSPELT ONE REFUSES, NAMING ONLY THE MISSPELT ONE.
//
// WRITTEN FOR A GAP THE EARLIER CASE COULD NOT REACH. `TestAValueTheRoutineDoesNotTake...` asserted
// that an unknown name is not SHOWN as something the routine will type, which was true — it was
// filtered out before the check ran, so it was not shown and not refused either. Supplying
// `message` and `mesage` therefore ran happily with the first and silently ignored the second,
// which is the one outcome this whole check exists to prevent.
//
// The refusal names the unknown one and not the good one, because the good one is not the problem.
func TestAValidValueBesideAMisspeltOneRefuses(t *testing.T) {
	d, rt := aRoutineWithAValue(t)
	i, err := d.PrepareInvocation(rt, map[string]string{
		"message": "the text I meant", "mesage": "the one I mistyped"})
	if err != nil {
		t.Fatalf("PrepareInvocation: %v", err)
	}
	if i.Runnable() {
		t.Fatal("a misspelt argument was dropped and the routine ran with the rest")
	}
	if !strings.Contains(i.Why, `"mesage"`) {
		t.Errorf("the refusal does not name the misspelt argument: %q", i.Why)
	}
	// AND IT DOES NOT BLAME THE ONE THAT WAS RIGHT.
	if strings.Contains(i.Why, `"message"`) &&
		!strings.Contains(i.Why, "it takes") {
		t.Errorf("the refusal blames the argument that was correct: %q", i.Why)
	}
	// AND NEITHER VALUE IS IN IT, because a refusal is a diagnostic.
	for _, v := range []string{"the text I meant", "the one I mistyped"} {
		if strings.Contains(i.Why, v) {
			t.Errorf("the refusal repeated a value: %q", i.Why)
		}
	}
}
