package orchestrator

// A REVIEW IS BOUND TO THE SOURCE IT SHOWED, AND SEPARATELY TO THE FILE ON DISK.
//
// Every review in this package puts the file as it stands on one side and what would be written on
// the other, and that left-hand side is the whole of what makes approving a replacement an approval
// of something somebody recognises. It is also an exported, mutable field.
//
// So two questions, and the token had only one of them:
//
//	WHAT CURRENTLY EXISTS    `sourceAt`, a digest read at preparation and compared against the
//	                         file again under the lock. It answers whether the routine on disk is
//	                         still the one this review was built from.
//	WHAT WAS DISPLAYED       `routes.DigestOf(Was)`, recomputed by `sealed` from the field itself.
//	                         It answers whether the review is still showing what it showed.
//
// The first does not imply the second. `sourceAt` is a STORED value: a caller that rewrote `Was`
// after preparation left it alone, so the token still matched, the write still went ahead, and what
// had been displayed as the file as it stands was something nobody ever read off disk. The bytes
// written were correct Marco either way — the harm is the other half of
// `Prepared.Token`'s own sentence, that somebody approved what they were shown.
//
// Held in three directions for each of the three review types, because two of them are the same
// claim from opposite ends and the third is the control that stops this file passing for a contract
// which refuses everything:
//
//	ONLY WHAT WAS SHOWN CHANGED    the write refuses, and no file is touched.
//	NOTHING CHANGED                 the write succeeds.
//	THE FILE ON DISK CHANGED        the write refuses, independently of the above.
//
// See [[ADR-273-a-routine-writes-down-what-it-does]].

import (
	"os"
	"strings"
	"testing"
)

// anotherSource is a source that is legal Marco, is not what any fixture here saved, and is
// recognisably not the file on disk.
const anotherSource = `// Auto-generated by ` + "`marco learn \"something else\"`" + `.
use os.

the App is a script.

do OS's Key with "f12".
`

// ── AN EDIT ──────────────────────────────────────────────────────────────────

func TestAnEditReviewIsBoundToTheSourceItShowed(t *testing.T) {
	t.Run("only what was shown changed", func(t *testing.T) {
		d, rt := aThreePressRoutine(t)
		e, err := d.PrepareEdit(rt, []StepEdit{{Op: EditWait, At: 3, To: 800}})
		if err != nil {
			t.Fatalf("preparing: %v", err)
		}
		before := inTheFolder(t, d, rt)
		shown := e
		shown.Was = anotherSource
		if err := d.SaveEdit(shown); err == nil {
			t.Fatal("an edit whose displayed source was rewritten was saved")
		} else if !strings.Contains(err.Error(), "not the one that was reviewed") {
			t.Errorf("the refusal is not about the review's identity: %v", err)
		}
		if got := inTheFolder(t, d, rt); got != before {
			t.Errorf("something was written:\n%s\nbecame\n%s", before, got)
		}
	})
	t.Run("nothing changed", func(t *testing.T) {
		d, rt := aThreePressRoutine(t)
		e, err := d.PrepareEdit(rt, []StepEdit{{Op: EditWait, At: 3, To: 800}})
		if err != nil {
			t.Fatalf("preparing: %v", err)
		}
		if err := d.SaveEdit(e); err != nil {
			t.Fatalf("an untouched review was refused: %v", err)
		}
		if !strings.Contains(sourceOf(t, d, rt), "Sleep with 800") {
			t.Error("the edit did not land")
		}
	})
	t.Run("the file on disk changed", func(t *testing.T) {
		d, rt := aThreePressRoutine(t)
		e, err := d.PrepareEdit(rt, []StepEdit{{Op: EditWait, At: 3, To: 800}})
		if err != nil {
			t.Fatalf("preparing: %v", err)
		}
		// THE FILE, AND NOT THE REVIEW. `Was` still holds what was displayed, so
		// the digest of the field matches and only the reading of disk does not.
		if err := d.Reg.Save(rt, sourceOf(t, d, rt)+"\n"); err != nil {
			t.Fatal(err)
		}
		if err := d.SaveEdit(e); err == nil {
			t.Fatal("an edit was saved over a play that had changed")
		} else if !strings.Contains(err.Error(), "saved again") {
			t.Errorf("the refusal is not about the file on disk: %v", err)
		}
	})
}

// ── A REBUILD ────────────────────────────────────────────────────────────────

func TestARebuildReviewIsBoundToTheSourceItShowed(t *testing.T) {
	t.Run("only what was shown changed", func(t *testing.T) {
		d, rt := aTypedRoutine(t, Coordinates)
		p, err := d.Prepare(rt, RebuildSimplifyTyping)
		if err != nil {
			t.Fatalf("preparing: %v", err)
		}
		before := inTheFolder(t, d, rt)
		shown := p
		shown.Was = anotherSource
		if err := d.Replace(shown); err == nil {
			t.Fatal("a rebuild whose displayed source was rewritten was written")
		} else if !strings.Contains(err.Error(), "not the one that was prepared") {
			t.Errorf("the refusal is not about the review's identity: %v", err)
		}
		if got := inTheFolder(t, d, rt); got != before {
			t.Errorf("something was written:\n%s\nbecame\n%s", before, got)
		}
	})
	t.Run("nothing changed", func(t *testing.T) {
		d, rt := aTypedRoutine(t, Coordinates)
		p, err := d.Prepare(rt, RebuildSimplifyTyping)
		if err != nil {
			t.Fatalf("preparing: %v", err)
		}
		if err := d.Replace(p); err != nil {
			t.Fatalf("an untouched review was refused: %v", err)
		}
		if sourceOf(t, d, rt) != p.Now {
			t.Error("what was written is not what the review said it would write")
		}
	})
	t.Run("the file on disk changed", func(t *testing.T) {
		d, rt := aTypedRoutine(t, Coordinates)
		p, err := d.Prepare(rt, RebuildSimplifyTyping)
		if err != nil {
			t.Fatalf("preparing: %v", err)
		}
		if err := d.Reg.Save(rt, sourceOf(t, d, rt)+"\n"); err != nil {
			t.Fatal(err)
		}
		if err := d.Replace(p); err == nil {
			t.Fatal("a rebuild was written over a play that had changed")
		} else if !strings.Contains(err.Error(), "saved again") {
			t.Errorf("the refusal is not about the file on disk: %v", err)
		}
	})
}

// ── A MOVE ───────────────────────────────────────────────────────────────────

func TestAMoveReviewIsBoundToTheSourceItShowed(t *testing.T) {
	t.Run("only what was shown changed", func(t *testing.T) {
		d, rt := anEditableUnguardedRoutine(t)
		m, err := d.PrepareRescope(rt, ScopeAppAnywhere, "notepad")
		if err != nil {
			t.Fatalf("preparing: %v", err)
		}
		before := inTheFolder(t, d, rt)
		shown := m
		shown.Was = anotherSource
		if _, err := d.Rescope(shown, shown.ConsentToReplace()); err == nil {
			t.Fatal("a move whose displayed source was rewritten was performed")
		} else if !strings.Contains(err.Error(), "not the one that was prepared") {
			t.Errorf("the refusal is not about the review's identity: %v", err)
		}
		if got := inTheFolder(t, d, rt); got != before {
			t.Errorf("something was written:\n%s\nbecame\n%s", before, got)
		}
		if _, err := os.ReadFile(d.Reg.Path(m.To)); err == nil {
			t.Error("a play was written at the destination")
		}
	})
	t.Run("nothing changed", func(t *testing.T) {
		d, rt := anEditableUnguardedRoutine(t)
		m, err := d.PrepareRescope(rt, ScopeAppAnywhere, "notepad")
		if err != nil {
			t.Fatalf("preparing: %v", err)
		}
		done, err := d.Rescope(m, m.ConsentToReplace())
		if err != nil {
			t.Fatalf("an untouched review was refused: %v", err)
		}
		if !done.Removed {
			t.Fatalf("the move did not complete: %s", done.Says)
		}
	})
	t.Run("the file on disk changed", func(t *testing.T) {
		d, rt := anEditableUnguardedRoutine(t)
		m, err := d.PrepareRescope(rt, ScopeAppAnywhere, "notepad")
		if err != nil {
			t.Fatalf("preparing: %v", err)
		}
		if err := d.Reg.Save(rt, sourceOf(t, d, rt)+"\n"); err != nil {
			t.Fatal(err)
		}
		if _, err := d.Rescope(m, m.ConsentToReplace()); err == nil {
			t.Fatal("a move was performed over a play that had changed")
		} else if !strings.Contains(err.Error(), "saved again") {
			t.Errorf("the refusal is not about the file on disk: %v", err)
		}
		if _, err := os.ReadFile(d.Reg.Path(rt)); err != nil {
			t.Errorf("the original is gone: %v", err)
		}
	})
}
